def form_controls(ctx: PageCtx, fields: list[dict]) -> tuple[str, str, str]:
    """→ (FormGroup init TS, html, pattern messages TS)."""
    ctx.imp("@angular/forms", "FormControl", "FormGroup", "Validators")
    ctrls, html, pmsg = [], [], {}
    for f in fields:
        v = f.get("validation", {})
        validators = []
        if f.get("required"):
            validators.append("Validators.required")
        if "minLength" in v:
            validators.append(f"Validators.minLength({v['minLength']})")
        if "maxLength" in v:
            validators.append(f"Validators.maxLength({v['maxLength']})")
        if "pattern" in v:
            validators.append(f"Validators.pattern({ts_lit(v['pattern'])})")
            if v.get("patternMessage"):
                pmsg[f["name"]] = v["patternMessage"]
        if "min" in v:
            validators.append(f"Validators.min({v['min']})")
        if "max" in v:
            validators.append(f"Validators.max({v['max']})")
        init = {"toggle": "false", "number": "null as number | null", "multiselect": "[] as unknown[]", "date": "null as Date | null",
                "datetime": "null as Date | null", "select": "null as unknown"}.get(f["control"], "''")
        ctrls.append(f"    {f['name']}: new FormControl({init}, {{ nonNullable: {'true' if init in ('false', chr(39)*2) else 'false'}, validators: [{', '.join(validators)}] }}),")
        cid = f"{ctx.sid}-{f['name']}"
        tid = f'data-testid="{ctx.sid}-field-{f["name"]}"'
        ph = f' placeholder="{attr(f["placeholder"])}"' if f.get("placeholder") else ""
        c = f["control"]
        if c == "text":
            ctl = f'<input pInputText id="{cid}" formControlName="{f["name"]}"{ph} {tid} />'
        elif c == "textarea":
            ctl = f'<textarea pTextarea id="{cid}" formControlName="{f["name"]}" rows="4"{ph} {tid}></textarea>'
        elif c == "password":
            ctl = f'<p-password inputId="{cid}" formControlName="{f["name"]}" [feedback]="false" [toggleMask]="true" {tid} />'
        elif c == "number":
            ctl = f'<p-inputnumber inputId="{cid}" formControlName="{f["name"]}" [useGrouping]="false" {tid} />'
        elif c in ("select", "multiselect"):
            tag = "p-select" if c == "select" else "p-multiselect"
            if f.get("optionsFrom"):
                name = camel(f"opts-{f['name']}")
                o = f["optionsFrom"]
                op = ctx.gen.ops[o["operationId"]]
                ctx.imp("../../../shared/state/loadable", "loadable")
                ctx.imp("../../../shared/screen/data-helpers", "itemsOf")
                ctx.members.append(f"  protected readonly {name}Src = loadable(() => this.api.{op.op_id}({params_obj(o.get('params'))}));")
                ctx.members.append(f"  protected readonly {name} = computed(() => itemsOf(this.{name}Src.data()).map((x) => ({{ label: String(x.{f.get('optionLabel', 'name')}), value: x.{f.get('optionValue', 'id')} }})));")
                ctx.ctor.append(f"    if (this.allowed()) this.{name}Src.load();")
                opts = f"{name}()"
            else:
                name = camel(f"opts-{f['name']}")
                ctx.members.append(f"  protected readonly {name} = {ts_lit(f.get('options', []))};")
                opts = name
            ctl = f'<{tag} inputId="{cid}" formControlName="{f["name"]}" [options]="{opts}" optionLabel="label" optionValue="value"{ph} {tid} />'
        elif c in ("date", "datetime"):
            time = ' [showTime]="true" hourFormat="24"' if c == "datetime" else ""
            ctl = f'<p-datepicker inputId="{cid}" formControlName="{f["name"]}" dateFormat="dd.mm.yy" [showIcon]="true"{time} {tid} />'
        else:  # toggle
            ctl = f'<p-toggleswitch inputId="{cid}" formControlName="{f["name"]}" {tid} />'
        req = ' class="sf-required"' if f.get("required") else ""
        hint = f'<small class="sf-hint">{attr(f["hint"])}</small>' if f.get("hint") else ""
        err = (f'@if (showError(form.controls.{f["name"]})) {{ <small class="sf-error" data-testid="{ctx.sid}-error-{f["name"]}">'
               f'{{{{ errorText(form.controls.{f["name"]}, patternMessages[\'{f["name"]}\']) }}}}</small> }}')
        html.append(f'<div class="sf-field"><label for="{cid}"{req}>{attr(f["label"])}</label>{ctl}{hint}{err}</div>')
    group = "  protected readonly form = new FormGroup({\n" + "\n".join(ctrls) + "\n  });"
    return group, "\n".join(html), f"  protected readonly patternMessages: Record<string, string | undefined> = {ts_lit(pmsg)};"


def build_form(ctx: PageCtx) -> str:
    s, form = ctx.screen, ctx.screen["form"]
    sub = form["submit"]
    op = ctx.gen.ops[sub["operationId"]]
    group, fields_html, pmsg = form_controls(ctx, form["fields"])
    ctx.members += [group, pmsg]
    ctx.imp("../../../shared/form/form-helpers", "applyServerErrors", "errorText", "showError", "toApiBody")
    ctx.imp("../../../core/http/problem", "problemMessage", "toProblem")
    ctx.imp("../../../core/http/idempotency", "newIdempotencyKey")
    ctx.imp("@angular/core", "signal")
    ctx.members += [
        "  protected readonly showError = showError;",
        "  protected readonly errorText = errorText;",
        "  protected readonly saving = signal(false);",
        "  protected readonly formError = signal<string | null>(null);",
        "  /** Один ключ на одно намерение: повторная отправка после сбоя не создаст дубль. */",
        "  private idempotencyKey = newIdempotencyKey();",
    ]
    if form.get("load"):
        lop = ctx.gen.ops[form["load"]["operationId"]]
        ctx.imp("../../../shared/state/loadable", "loadable")
        ctx.members.append(f"  protected readonly primary = loadable(() => this.api.{lop.op_id}({params_obj(form['load'].get('params'))}));")
        ctx.members.append("  protected override reload(silent = false): void { this.primary.load({ silent }); }")
        ctx.members.append("  protected readonly view = computed(() => this.status(this.primary.status()));")
        ctx.ctor.append("    effect(() => { const d = this.primary.data(); if (d) this.form.patchValue(d as never); });")
        ctx.imp("@angular/core", "effect")
        problem = "primary.problem()"
    else:
        ctx.members.append("  protected override reload(): void { /* форма создания — загружать нечего */ }")
        ctx.members.append("  protected readonly view = computed(() => this.status('ready'));")
        problem = "null"
    ctx.imp("@angular/core", "computed")
    nav = f"\n        this.go({link_ts_expr(ctx, sub['navigateTo'], sub.get('params'))});" if sub.get("navigateTo") else ""
    args = []
    if op.body_type:
        args.append(f"toApiBody(this.form.getRawValue()) as unknown as {op.body_type}")
    args.append(params_obj(sub.get("params")))
    args.append("{ idempotencyKey: " + ("this.idempotencyKey" if sub.get("idempotent", True) else "undefined") + ", silent: true }")
    ctx.members.append(f"""  protected submit(): void {{
    if (this.form.invalid) {{
      this.form.markAllAsTouched();
      return;
    }}
    this.saving.set(true);
    this.formError.set(null);
    this.api.{op.op_id}({', '.join(args)}).subscribe({{
      next: () => {{
        this.saving.set(false);
        this.idempotencyKey = newIdempotencyKey();
        this.messages.add({{ severity: 'success', summary: {ts_str(sub['successMessage'])}, life: 4000 }});{nav}
      }},
      error: (err: unknown) => {{
        this.saving.set(false);
        const p = toProblem(err);
        this.formError.set(problemMessage(p));
        applyServerErrors(this.form, p);
      }},
    }});
  }}""")
    cancel = "".join(action_button(ctx, a, None) for a in s.get("actions", []))
    er = s["states"]["error"]
    return "\n".join(x for x in [
        f'<div class="sf-page" data-testid="{ctx.sid}">',
        header_html(ctx, attr(s["title"])),
        f'<app-state {state_attrs(ctx, s["states"], "view()", problem, "detail")}>',
        "<p-card>",
        f'<form [formGroup]="form" (ngSubmit)="submit()" class="sf-form" novalidate data-testid="{ctx.sid}-form">',
        f'@if (formError()) {{ <p-message severity="error" data-testid="{ctx.sid}-form-error"><strong>{attr(er["title"])}</strong>: {{{{ formError() }}}}</p-message> }}',
        fields_html,
        f'<div class="sf-row"><p-button type="submit" label="{attr(sub["label"])}" icon="pi pi-check" [loading]="saving()" data-testid="{ctx.sid}-submit" />{cancel}</div>',
        "</form>", "</p-card>", "</app-state>", "</div>",
    ] if x)


def build_generic(ctx: PageCtx) -> str:
    s = ctx.screen
    if s.get("data"):
        add_sources(ctx)
        ctx.members.append("  protected readonly view = computed(() => this.status(this.primary.status()));")
        problem = "primary.problem()"
    else:
        ctx.members.append("  protected override reload(): void { /* нет источников */ }")
        ctx.members.append("  protected readonly slotData = computed(() => ({}));")
        ctx.members.append("  protected readonly view = computed(() => this.status('ready'));")
        ctx.imp("@angular/core", "computed")
        problem = "null"
    allslots = "\n".join(slot_tag(ctx, sl, "slotData()") for sl in s.get("slots", []) if sl["placement"] != "header")
    return "\n".join(x for x in [
        f'<div class="sf-page" data-testid="{ctx.sid}">',
        header_html(ctx, attr(s["title"]), screen_actions(ctx, None)),
        f'<app-state {state_attrs(ctx, s["states"], "view()", problem, "detail")}>',
        f'<div class="sf-stack">{allslots}</div>',
        "</app-state>", "</div>",
    ] if x)


