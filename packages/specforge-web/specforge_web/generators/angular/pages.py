def filters_html(ctx: PageCtx, filters: list[dict], search: dict | None) -> str:
    if not filters and not search:
        return ""
    parts = []
    if search:
        ph = attr(search.get("placeholder", "Поиск"))
        parts.append(
            '<p-iconfield iconPosition="left"><p-inputicon styleClass="pi pi-search" />'
            f'<input pInputText type="search" placeholder="{ph}" aria-label="{ph}" [value]="list.search()"'
            f' (keyup.enter)="list.setSearch($any($event.target).value)" (search)="list.setSearch($any($event.target).value)"'
            f' (blur)="list.setSearch($any($event.target).value)" data-testid="{ctx.sid}-search" /></p-iconfield>')
    for f in filters:
        param = f.get("param") or f["field"]
        tid = f'{ctx.sid}-filter-{f["field"]}'
        label = attr(f["label"])
        if f.get("optionsFrom"):
            name = camel(f"opts-{f['field']}")
            o = f["optionsFrom"]
            op = ctx.gen.ops[o["operationId"]]
            ctx.imp("../../../shared/state/loadable", "loadable")
            ctx.imp("../../../shared/screen/data-helpers", "itemsOf")
            ctx.members.append(f"  protected readonly {name}Src = loadable(() => this.api.{op.op_id}({params_obj(o.get('params'))}));")
            lbl, val = f.get("optionLabel", "name"), f.get("optionValue", "id")
            ctx.members.append(f"  protected readonly {name} = computed(() => itemsOf(this.{name}Src.data()).map((x) => ({{ label: String(x.{lbl}), value: x.{val} }})));")
            ctx.ctor.append(f"    if (this.allowed()) this.{name}Src.load();")
            options = f"{name}()"
        else:
            name = camel(f"opts-{f['field']}")
            ctx.members.append(f"  protected readonly {name} = {ts_lit(f.get('options', []))};")
            options = name
        if f["control"] in ("select", "multiselect"):
            tag = "p-select" if f["control"] == "select" else "p-multiselect"
            parts.append(f'<{tag} [options]="{options}" optionLabel="label" optionValue="value" [showClear]="true"'
                         f' placeholder="{label}" [ngModel]="list.query()[\'{param}\']" (ngModelChange)="list.setFilter(\'{param}\', $event)"'
                         f' styleClass="sf-filter" data-testid="{tid}" />')
        elif f["control"] == "date-range":
            parts.append(f'<p-datepicker selectionMode="range" [readonlyInput]="true" [showIcon]="true" [showButtonBar]="true" dateFormat="dd.mm.yy"'
                         f' placeholder="{label}" (ngModelChange)="list.setRange(\'{param}\', $event)" [ngModel]="null"'
                         f' styleClass="sf-filter" data-testid="{tid}" />')
        elif f["control"] == "toggle":
            parts.append(f'<span class="sf-row"><p-toggleswitch inputId="{tid}" [ngModel]="!!list.query()[\'{param}\']"'
                         f' (ngModelChange)="list.setFilter(\'{param}\', $event || undefined)" data-testid="{tid}" /><label for="{tid}">{label}</label></span>')
        else:
            parts.append(f'<input pInputText placeholder="{label}" aria-label="{label}" (keyup.enter)="list.setFilter(\'{param}\', $any($event.target).value)"'
                         f' (blur)="list.setFilter(\'{param}\', $any($event.target).value)" data-testid="{tid}" />')
    clear = (f'@if (list.hasFilters()) {{ <p-button label="Сбросить" icon="pi pi-filter-slash" [text]="true" severity="secondary"'
             f' (onClick)="list.clear()" data-testid="{ctx.sid}-filters-clear" /> }}')
    return (f'<p-toolbar styleClass="sf-toolbar">\n  <ng-template #start><div class="sf-row">{"".join(parts)}</div></ng-template>\n'
            f'  <ng-template #end>{clear}</ng-template>\n</p-toolbar>')


