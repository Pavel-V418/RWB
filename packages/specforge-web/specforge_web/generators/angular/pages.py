# ---------------------------------------------------------------- imports from html
def resolve_ng_imports(html: str, manifest: dict, ctx: PageCtx) -> list[str]:
    tags = {t.lower() for t in re.findall(r"<(p-[a-zA-Z-]+)", html)}
    by_tag = {c["tag"].lower(): c for c in manifest["components"]}
    mods: dict[str, str] = {}
    for t in tags:
        c = by_tag.get(t)
        if c:
            mods[c["module"]] = c["from"]
    for d in manifest["directives"]:
        if re.search(rf"\b{d['attr']}\b", html):
            mods[d["module"]] = d["from"]
    for mod, src in mods.items():
        ctx.imp(src, mod)
    names = sorted(mods)
    if "<app-state" in html:
        ctx.imp("../../../shared/state/app-state.component", "AppStateComponent")
        names.append("AppStateComponent")
    if "<app-value" in html:
        ctx.imp("../../../shared/value/app-value.component", "AppValueComponent")
        names.append("AppValueComponent")
    if "<app-map" in html:
        ctx.imp("../../../shared/map/app-map.component", "AppMapComponent")
        names.append("AppMapComponent")
    if "routerLink" in html:
        ctx.imp("@angular/router", "RouterLink")
        names.append("RouterLink")
    if "formGroup" in html:
        ctx.imp("@angular/forms", "ReactiveFormsModule")
        names.append("ReactiveFormsModule")
    if "ngModel" in html:
        ctx.imp("@angular/forms", "FormsModule")
        names.append("FormsModule")
    names += [cls for cls, _ in ctx.slot_components]
    return names


def render_ts(ctx: PageCtx, class_name: str, ng_imports: list[str]) -> str:
    s = ctx.screen
    ctx.imp("@angular/core", "ChangeDetectionStrategy", "Component")
    ctx.imp("../../../shared/screen/screen-base", "ScreenBase")
    if "sev(" in "\n".join(ctx.members) or ctx.uses_sev:
        ctx.imp("../../../shared/value/format", "toSeverity")
    if ctx.maps:
        ctx.imp("../../../shared/value/format", "StatusMap")
    model_names = {pascal(k) for k in ctx.gen.schemas}
    used = set(re.findall(r"\b[A-Z][A-Za-z0-9]*\b", "\n".join(ctx.members + ctx.ctor)))
    for name in sorted(used & model_names):
        ctx.imp("../../api/models", name)
    lines = [GEN_HEADER.format(app=ctx.app["id"], screen=s["id"])]
    order = sorted(ctx.ts_imports, key=lambda m: (not m.startswith("@"), not m.startswith("primeng"), m.startswith("."), m))
    prev_group = None
    for mod in order:
        group = 0 if mod.startswith("@") or mod.startswith("primeng") or mod == "rxjs" else 1
        if prev_group is not None and group != prev_group:
            lines.append("")
        prev_group = group
        lines.append(f"import {{ {', '.join(sorted(ctx.ts_imports[mod]))} }} from '{mod}';")
    lines.append("")
    if (s.get("list") or {}).get("tabs"):
        tabs = [{"label": t["label"], "params": t["params"]} for t in s["list"]["tabs"]]
        lines.append(f"const TABS: {{ label: string; params: Record<string, string> }}[] = {ts_lit(tabs)};")
        lines.append("")
    if s.get("requirements"):
        lines.append(f"/** Требования: {', '.join(s['requirements'])}. {s.get('description', '')}".rstrip() + " */")
    lines += [
        "@Component({",
        f"  selector: 'page-{s['id']}',",
        f"  imports: [{', '.join(ng_imports)}],",
        f"  templateUrl: './{s['id']}.page.html',",
        "  changeDetection: ChangeDetectionStrategy.OnPush,",
        "})",
        f"export class {class_name} extends ScreenBase {{",
        f"  protected override readonly roles = {ts_lit(s['roles'])};",
    ]
    if ctx.maps:
        maps = ",\n".join(f"    {name}: {key} as StatusMap" for key, name in ctx.maps.items())
        lines.append(f"  protected readonly maps = {{\n{maps},\n  }};")
    if ctx.uses_sev:
        lines.append("  protected readonly sev = toSeverity;")
    lines += ctx.members
    if ctx.ctor:
        lines += ["", "  constructor() {", "    super();", *ctx.ctor, "  }"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def build_page(app: dict, screen: dict, spec: dict, gen: TsGen, manifest: dict) -> dict:
    ctx = PageCtx(app=app, screen=screen, spec=spec, gen=gen)
    ctx.uses_sev = False  # type: ignore[attr-defined]
    realtime_members(ctx, "primary" if screen["archetype"] in ("list", "timeline") else None)
    html = BUILDERS[screen["archetype"]](ctx)
    # actions
    item_t = None
    if screen["archetype"] == "detail":
        op = ctx.source_op("primary")
        item_t = op.item_type if op else None
    elif screen["archetype"] == "list":
        op = ctx.source_op("primary")
        item_t = op.item_type if op else None
        if item_t:
            ctx.imp("../../api/models", *re.findall(r"\b[A-Z][A-Za-z0-9]*\b", item_t))
    for a in screen.get("actions", []):
        ctx.members.append(action_method(ctx, a, item_t))
    if "current()" in "\n".join(ctx.members) and not any("readonly current" in m for m in ctx.members):
        ctx.members.append("  protected current(): unknown { return null; }")
    ctx.uses_sev = "sev(" in html  # type: ignore[attr-defined]
    ng_imports = resolve_ng_imports(html, manifest, ctx)
    class_name = pascal(screen["id"]) + "Page"
    ts = render_ts(ctx, class_name, ng_imports)
    return {"class": class_name, "ts": ts, "html": html + "\n", "slots": ctx.slot_components}
