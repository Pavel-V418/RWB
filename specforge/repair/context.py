"""Узкий контекст для ремонта: только то, что нужно для конкретных диагностик.

На каждую диагностику: место ошибки (code_window), сигнатуры упомянутых в сообщении символов
(поиск определений по имени) и — если ошибка в сгенерированном или защищённом коде —
связанный фрагмент контракта (OpenAPI/AsyncAPI-схема, DDL). Общий объём ограничен
REPAIR_CONTEXT_TOKENS: диагностики идут в порядке приоритета шлюза, не поместившиеся
перечисляются одной строкой.
"""

import os
import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from functools import cached_property
from pathlib import Path

from pydantic import BaseModel

from specforge.core.contracts import Diagnostic
from specforge.tools.base import glob_match

REPAIR_CONTEXT_TOKENS = int(os.environ.get("REPAIR_CONTEXT_TOKENS", "6000"))
CHARS_PER_TOKEN = 4
MAX_SYMBOLS = 3
MAX_DEFINITIONS = 2
MAX_CONTRACT_LINES = 40
MAX_FILE_BYTES = 500_000
SOURCE_SUFFIXES = frozenset(
    {".cs", ".ts", ".tsx", ".js", ".kt", ".kts", ".java", ".py", ".sql", ".html", ".go", ".rs"}
)
CONTRACT_GLOBS = (
    "**/openapi*.yaml", "**/openapi*.yml", "**/openapi*.json",
    "**/asyncapi*.yaml", "**/asyncapi*.yml", "**/asyncapi*.json",
    "**/*.proto", "**/schema*.sql", "**/migrations/*.sql",
)  # fmt: skip
SKIP_DIRS = frozenset(
    {".git", ".specforge", "node_modules", "bin", "obj", "build", ".gradle", "dist", ".venv"}
)
GENERATED_MARKERS = ("<auto-generated", "auto-generated", "code generated", "do not edit")
_QUOTED_RE = re.compile(r"['\"`‘“]([A-Za-z_$][\w$.]*)['\"`’”]")
_NOISE = frozenset(
    {"string", "number", "boolean", "bool", "int", "long", "double", "float", "void", "null",
     "undefined", "object", "any", "unknown", "never", "true", "false", "this", "var", "let",
     "Int", "String", "Boolean", "Unit", "Any", "Object", "List", "Task", "Guid"}
)  # fmt: skip
_TYPE_SUFFIXES = ("Dto", "DTO", "Request", "Response", "Model", "Entity", "Event", "Message")


class RepairContext(BaseModel):
    text: str
    included: int
    omitted: int
    symbols: list[str]


@dataclass
class _Workspace:
    root: Path
    protected_globs: Sequence[str] = field(default_factory=tuple)

    @cached_property
    def sources(self) -> list[tuple[str, list[str]]]:
        """(путь относительно /work, строки) всех исходников — читается один раз."""
        result: list[tuple[str, list[str]]] = []
        for path in sorted(self.root.rglob("*")):
            rel = path.relative_to(self.root)
            if any(part in SKIP_DIRS for part in rel.parts) or path.suffix not in SOURCE_SUFFIXES:
                continue
            if not path.is_file() or path.stat().st_size > MAX_FILE_BYTES:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            result.append((rel.as_posix(), text.splitlines()))
        return result

    @cached_property
    def contracts(self) -> list[tuple[str, list[str]]]:
        found: dict[str, list[str]] = {}
        for pattern in CONTRACT_GLOBS:
            for path in sorted(self.root.glob(pattern)):
                rel = path.relative_to(self.root)
                if path.is_file() and not any(p in SKIP_DIRS for p in rel.parts):
                    found.setdefault(
                        rel.as_posix(),
                        path.read_text(encoding="utf-8", errors="replace").splitlines(),
                    )
        return list(found.items())

    def is_generated(self, rel: str) -> bool:
        if any(glob_match(rel, g) for g in self.protected_globs):
            return True
        if re.search(r"(^|/)generated(/|$)|\.g\.|\.generated\.", rel, re.IGNORECASE):
            return True
        target = self.root / rel
        if not target.is_file():
            return False
        head = "\n".join(target.read_text(encoding="utf-8", errors="replace").splitlines()[:5])
        return any(marker in head.lower() for marker in GENERATED_MARKERS)


def build_repair_context(
    diagnostics: Sequence[Diagnostic],
    workspace: Path,
    *,
    protected_globs: Sequence[str] = (),
    budget_tokens: int | None = None,
) -> RepairContext:
    budget_chars = (budget_tokens or REPAIR_CONTEXT_TOKENS) * CHARS_PER_TOKEN
    ws = _Workspace(workspace.resolve(), protected_globs)
    sections: list[str] = []
    used = 0
    symbols_seen: list[str] = []
    omitted: list[Diagnostic] = []
    for number, diagnostic in enumerate(diagnostics, 1):
        if omitted:
            omitted.append(diagnostic)
            continue
        symbols = extract_symbols(diagnostic.message)
        section = _section(number, diagnostic, symbols, ws)
        if used + len(section) > budget_chars and sections:
            omitted.append(diagnostic)
            continue
        if used + len(section) > budget_chars:  # первая диагностика не влезает — усечём её
            section = section[: max(0, budget_chars - 40)] + "\n…[усечено]"
        sections.append(section)
        used += len(section)
        symbols_seen += [s for s in symbols if s not in symbols_seen]
    if omitted:
        tail = "; ".join(_title(d) for d in omitted)
        sections.append(f"Не вошли в контекст ({len(omitted)}): {tail[:600]}")
    return RepairContext(
        text="\n\n".join(sections),
        included=len(diagnostics) - len(omitted),
        omitted=len(omitted),
        symbols=symbols_seen,
    )


def extract_symbols(message: str) -> list[str]:
    """Имена в кавычках из сообщения (`'orderSvc'`, `"Name"`), без встроенных типов."""
    result: list[str] = []
    for match in _QUOTED_RE.finditer(message):
        name = match.group(1).rsplit(".", 1)[-1]
        if len(name) < 2 or name in _NOISE or name in result:
            continue
        result.append(name)
        if len(result) >= MAX_SYMBOLS:
            break
    return result


def find_definitions(symbol: str, sources: list[tuple[str, list[str]]]) -> list[str]:
    """Строки-определения символа: `class X`, `fun x(`, `public T X {`, `x: T;`."""
    escaped = re.escape(symbol)
    patterns = [
        re.compile(
            r"\b(class|interface|record|struct|enum|object|fun|def|function|type|val|var|"
            rf"const|let|table)\s+(\w+\.)?{escaped}\b",
            re.IGNORECASE if symbol.islower() else 0,
        ),
        re.compile(rf"\b(public|private|protected|internal)\b[^=;{{]*\b{escaped}\s*[({{=;<]"),
        re.compile(rf"^\s*(readonly\s+)?{escaped}\??\s*:\s*\S"),
    ]
    hits: list[str] = []
    for rel, lines in sources:
        for number, line in enumerate(lines, 1):
            if any(p.search(line) for p in patterns):
                hits.append(f"{rel}:{number}: {line.strip()[:200]}")
                if len(hits) >= MAX_DEFINITIONS:
                    return hits
    return hits


def contract_fragment(names: Sequence[str], ws: _Workspace) -> str | None:
    """Блок контракта, описывающий одно из имён: ключ YAML с вложенными строками,
    иначе — окрестность первого упоминания."""
    for name in names:
        for rel, lines in ws.contracts:
            for index, line in enumerate(lines):
                match = re.match(rf"^(\s*)['\"]?{re.escape(name)}['\"]?\s*:\s*$", line)
                if match:
                    indent = len(match.group(1))
                    block = [line]
                    for follow in lines[index + 1 :]:
                        if follow.strip() and len(follow) - len(follow.lstrip()) <= indent:
                            break
                        block.append(follow)
                        if len(block) >= MAX_CONTRACT_LINES:
                            break
                    return _numbered(rel, index + 1, block)
        for rel, lines in ws.contracts:
            for index, line in enumerate(lines):
                if re.search(rf"\b{re.escape(name)}\b", line):
                    start = max(0, index - 5)
                    return _numbered(rel, start + 1, lines[start : index + 10])
    return None


def _section(number: int, d: Diagnostic, symbols: list[str], ws: _Workspace) -> str:
    parts = [f"### {number}. {_title(d)}", d.message.strip()]
    if d.code_window:
        parts.append(f"```\n{d.code_window}\n```")
    definitions = [
        f"- {symbol}: "
        + (
            "; ".join(found)
            if (found := find_definitions(symbol, ws.sources))
            else "определение не найдено"
        )
        for symbol in symbols
    ]
    if definitions:
        parts.append("Упомянутые символы:\n" + "\n".join(definitions))
    if d.file and ws.is_generated(d.file):
        names = [*symbols, *_type_names(d.file)]
        fragment = contract_fragment(names, ws)
        note = (
            "Файл сгенерирован из контракта или защищён — правьте не его, "
            "а код, который его использует."
        )
        parts.append(note + (f"\nСвязанный фрагмент контракта:\n{fragment}" if fragment else ""))
    return "\n".join(parts)


def _title(d: Diagnostic) -> str:
    where = d.file or "?"
    if d.line:
        where += f":{d.line}" + (f":{d.column}" if d.column else "")
    code = f" {d.code}" if d.code else ""
    return f"[{d.category or 'generic'}] {d.tool}{code} — {where}"


def _type_names(rel: str) -> list[str]:
    stem = Path(rel).name.split(".")[0]
    names = [stem]
    for suffix in _TYPE_SUFFIXES:
        if stem.endswith(suffix) and len(stem) > len(suffix):
            names.append(stem[: -len(suffix)])
    return names


def _numbered(rel: str, first: int, lines: list[str]) -> str:
    body = "\n".join(f"{first + i:>5} | {line}" for i, line in enumerate(lines))
    return f"{rel}:\n```\n{body}\n```"
