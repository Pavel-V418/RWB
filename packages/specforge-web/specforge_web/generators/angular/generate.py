"""SpecForge Angular generator: screen-spec + OpenAPI → готовый проект админки. Без LLM.

  python -m generators.angular.generate --spec S.json --openapi O.yaml --out DIR [--events E.json]

Что делает:
  1. копирует золотой каркас (scaffolds/angular-admin) и дизайн-систему;
  2. генерирует API-клиент (models.ts, api.service.ts) из OpenAPI;
  3. генерирует страницы по архетипам + unit-тесты состояний;
  4. генерирует маршруты, меню, витрину UI Kit (/__kit), e2e-обход экранов;
  5. создаёт заглушки слотов (их заполняет frontend-агент; существующие не перезаписываются);
  6. пишет generation-report.json и slots.json (задания для LLM).
Повторный запуск идемпотентен: перезаписывается только generated/, слоты сохраняются.
"""
from __future__ import annotations

import argparse
