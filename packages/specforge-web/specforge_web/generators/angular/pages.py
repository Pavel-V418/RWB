def camel(s: str) -> str:
    p = pascal(s)
    return p[:1].lower() + p[1:]


def attr(s: str) -> str:
    return escape(str(s), quote=True)


def ts_str(s: str) -> str:
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_lit(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def field_expr(var: str, path: str) -> str:
    parts = path.split(".")
    return var + "." + "?.".join(parts) if len(parts) > 1 else f"{var}.{path}"


@dataclass
class PageCtx:
    app: dict
    screen: dict
    spec: dict
    gen: TsGen
    members: list[str] = field(default_factory=list)
    ctor: list[str] = field(default_factory=list)
    ts_imports: dict[str, set[str]] = field(default_factory=dict)
    maps: dict[str, str] = field(default_factory=dict)  # json → name
    slot_components: list[tuple[str, str]] = field(default_factory=list)  # (class, file)
    uses_sev: bool = False

    @property
    def sid(self) -> str:
        return self.screen["id"]

    def imp(self, module: str, *names: str) -> None:
        self.ts_imports.setdefault(module, set()).update(names)

    def status_map(self, sm: dict | None) -> str:
        if not sm:
            return "undefined"
        key = json.dumps(sm, ensure_ascii=False, sort_keys=True)
        if key not in self.maps:
            self.maps[key] = f"m{len(self.maps) + 1}"
        return f"maps.{self.maps[key]}"

    def screen_by_id(self, sid: str) -> dict:
        return next(s for s in self.spec["screens"] if s["id"] == sid)

    def source_op(self, src: str) -> OpMeta | None:
        data = self.screen.get("data") or {}
        ds = data.get("primary") if src == "primary" else (data.get("secondary") or {}).get(src)
        return self.gen.ops.get(ds["operationId"]) if ds else None


# ---------------------------------------------------------------- bindings & links
def binding_ts(b: str, item_var: str = "item") -> str:
    kind, _, val = b.partition(":")
    if kind == "route":
        return f"this.routeParam({ts_str(val)})"
    if kind == "query":
        return f"(this.route.snapshot.queryParamMap.get({ts_str(val)}) ?? undefined)"
    if kind == "context":
        return f"this.context({ts_str(val)})"
    if kind == "filter":
        return f"this.list.query()[{ts_str(val)}]"
    if kind == "item":
        return f"{item_var}?.{val}"
    if re.fullmatch(r"-?\d+", val):
        return val
    if val in ("true", "false"):
        return val
    return ts_str(val)


def params_obj(params: dict | None, item_var: str = "item") -> str:
    if not params:
        return "{}"
    return "{ " + ", ".join(f"{k}: {binding_ts(v, item_var)}" for k, v in params.items()) + " }"


def route_segments(route: str, value_for) -> list[str]:
    """'/things/:id' → ["'/things'", <expr for id>] (для [routerLink] и router.navigate)."""
    segs: list[str] = []
    static: list[str] = []

    def flush() -> None:
        if static:
            prefix = "/" if not segs else ""  # абсолютный путь задаёт только первый сегмент
            segs.append(ts_str(prefix + "/".join(static)))
            static.clear()

    for part in route.strip("/").split("/"):
        if not part:
            continue
        if part.startswith(":"):
            flush()
            if not segs:
                segs.append("'/'")
            segs.append(value_for(part[1:]))
        else:
            static.append(part)
    flush()
    return segs or ["'/'"]


def link_html_expr(ctx: PageCtx, target: str, var: str, param_field: str | None) -> str:
    route = ctx.screen_by_id(target)["route"]
    segs = route_segments(route, lambda name: field_expr(var, param_field or name))
    return "[" + ", ".join(segs) + "]"


def link_ts_expr(ctx: PageCtx, target: str, params: dict | None, item_var: str = "item") -> str:
    route = ctx.screen_by_id(target)["route"]
    params = params or {}

    def value_for(name: str) -> str:
        if name in params:
            return binding_ts(params[name], item_var)
        return f"this.routeParam({ts_str(name)})"

    return "[" + ", ".join(route_segments(route, value_for)) + "]"


# ---------------------------------------------------------------- shared html pieces
def value_html(ctx: PageCtx, f: dict, var: str) -> str:
    expr = field_expr(var, f["field"])
    fmt = f.get("format", "text")
    empty = f.get("emptyText", "—")
    if fmt == "link" and f.get("linkTo"):
        link = link_html_expr(ctx, f["linkTo"], var, f.get("linkParam"))
        testid = f"{ctx.sid}-link-{f['linkTo']}"
        if not f.get("label"):
            return f'<a class="sf-row-link" [routerLink]="{link}" aria-label="Открыть" data-testid="{testid}"><i class="pi pi-angle-right" aria-hidden="true"></i></a>'
        return f'<a class="sf-row-link" [routerLink]="{link}" data-testid="{testid}">{{{{ {expr} }}}}</a>'
    sm = f' [statusMap]="{ctx.status_map(f.get("statusMap"))}"' if fmt == "status" else ""
    return f'<app-value [value]="{expr}" format="{fmt}"{sm} emptyText="{attr(empty)}" />'


def hide_class(f: dict) -> str:
    return f' class="sf-hide-below-{f["hideBelow"]}"' if f.get("hideBelow") else ""


def table_html(ctx: PageCtx, columns: list[dict], rows_expr: str, testid: str, lazy: bool, row_link: dict | None,
               row_actions: list[dict], total_expr: str = "", busy_expr: str = "false", page_size: int = 20) -> str:
    head = []
    for c in columns:
        sort = f' pSortableColumn="{c["field"]}"' if lazy and c.get("sortable") else ""
        icon = f' <p-sortIcon field="{c["field"]}" />' if sort else ""
        head.append(f'<th{hide_class(c)}{sort}>{attr(c["label"])}{icon}</th>')
    if row_actions:
        head.append('<th class="sf-actions-col"><span class="sf-hide-below-sm">Действия</span></th>')
    cells = [f'<td{hide_class(c)}>{value_html(ctx, c, "row")}</td>' for c in columns]
    if row_actions:
        btns = "".join(action_button(ctx, a, "row", compact=True) for a in row_actions)
        cells.append(f'<td class="sf-actions-col"><div class="sf-row">{btns}</div></td>')
    tr_attrs = f' data-testid="{testid}-row"'
    if row_link:
        link = link_html_expr(ctx, row_link["target"], "row", row_link.get("param"))
        tr_attrs += f' class="sf-clickable" [routerLink]="{link}"'
    lazy_attrs = ""
    if lazy:
        lazy_attrs = (f' [lazy]="true" [lazyLoadOnInit]="false" (onLazyLoad)="list.onLazyLoad($event)" [paginator]="{total_expr} > {page_size}"'
                      f' [rows]="{page_size}" [first]="list.first()" [totalRecords]="{total_expr}" [loading]="{busy_expr}"')
    return (
        f'<p-table [value]="{rows_expr}" dataKey="id" [rowHover]="true" [scrollable]="true"{lazy_attrs} data-testid="{testid}">\n'
        f'  <ng-template #header><tr>{"".join(head)}</tr></ng-template>\n'
        f'  <ng-template #body let-row><tr{tr_attrs}>{"".join(cells)}</tr></ng-template>\n'
        f'</p-table>'
    )


def timeline_html(ctx: PageCtx, tl: dict, items_expr: str, testid: str) -> str:
    title_map = tl.get("titleMap")
    if title_map:
        tm = ctx.status_map({k: {"label": v, "severity": "info"} for k, v in title_map.items()})
        title = f'<p-tag [value]="{tm}[ev.{tl["titleField"]}]?.label ?? ev.{tl["titleField"]}" [severity]="sev(ev.{tl.get("severityField", "severity")}, {ctx.status_map(tl.get("statusMap"))})" />'
    elif tl.get("severityField"):
        title = (f'<span class="sf-row"><p-tag [value]="\'\'" [severity]="sev(ev.{tl["severityField"]}, {ctx.status_map(tl.get("statusMap"))})" [rounded]="true" />'
                 f'<strong>{{{{ ev.{tl["titleField"]} }}}}</strong></span>')
    else:
        title = f'<strong>{{{{ ev.{tl["titleField"]} }}}}</strong>'
    desc = f'<div>{{{{ ev.{tl["descriptionField"]} }}}}</div>' if tl.get("descriptionField") else ""
    link = ""
    if tl.get("linkTo"):
        lp = tl.get("linkParam") or "id"
        link_expr = link_html_expr(ctx, tl["linkTo"], "ev", lp)
        link = f'@if (ev.{lp}) {{ <a class="sf-row-link sf-text-sm" [routerLink]="{link_expr}" data-testid="{testid}-link">Открыть</a> }}'
    return (
        f'<p-timeline [value]="{items_expr}" align="left" styleClass="sf-timeline" data-testid="{testid}">\n'
        f'  <ng-template #content let-ev>\n'
        f'    <div class="sf-tl-item" data-testid="{testid}-item">\n'
        f'      <div class="sf-row sf-row--between">{title}<span class="sf-tl-time"><app-value [value]="ev.{tl["timeField"]}" format="relative-time" /></span></div>\n'
        f'      {desc}{link}\n'
        f'    </div>\n'
        f'  </ng-template>\n'
        f'</p-timeline>'
    )


def state_attrs(ctx: PageCtx, states: dict, status_expr: str, problem_expr: str, skeleton: str, compact: bool = False,
                testid: str | None = None, retry: str = "reload()") -> str:
    loading = states["loading"]["kind"]
    a = [f'[status]="{status_expr}"', f'loadingKind="{loading}"', f'skeleton="{skeleton}"',
         f'testid="{testid or ctx.sid + "-state"}"', f'[problem]="{problem_expr}"', f'(retry)="{retry}"']
    e = states["empty"]
    a.append(f'emptyTitle="{attr(e["title"])}"')
    if e.get("description"):
        a.append(f'emptyDescription="{attr(e["description"])}"')
    if e.get("actionId"):
        act = next((x for x in ctx.screen.get("actions", []) if x["id"] == e["actionId"]), None)
        if act:
            a.append(f'emptyActionLabel="{attr(act["label"])}"')
            a.append(f'(emptyAction)="{camel("act-" + act["id"])}()"')
    er = states["error"]
    a.append(f'errorTitle="{attr(er["title"])}"')
    if er.get("description"):
        a.append(f'errorDescription="{attr(er["description"])}"')
    if er.get("retry") is False:
        a.append('[retryable]="false"')
    fb = states["forbidden"]
    a.append(f'forbiddenTitle="{attr(fb["title"])}"')
    if fb.get("description"):
        a.append(f'forbiddenDescription="{attr(fb["description"])}"')
    if compact:
        a.append('[compact]="true"')
    return " ".join(a)


def section_state(ctx: PageCtx, src: str, empty_text: str | None, skeleton: str, body: str) -> str:
    states = {
        "loading": {"kind": "skeleton"},
        "empty": {"title": empty_text or "Данных нет"},
        "error": {"title": "Не удалось загрузить блок"},
        "forbidden": {"title": "Нет доступа к этим данным"},
    }
    tid = f"{ctx.sid}-{src}-state"
    attrs = state_attrs(ctx, {**states, "ready": {}}, f"{src}.status()", f"{src}.problem()", skeleton, compact=True,
                        testid=tid, retry=f"{src}.load()")
    return f"<app-state {attrs}>\n{body}\n</app-state>"


# ---------------------------------------------------------------- actions
def action_method(ctx: PageCtx, a: dict, item_type: str | None) -> str:
    name = camel("act-" + a["id"])
    item_arg = f"item?: {item_type} | null" if item_type else "item?: unknown"
    body: list[str] = []
    if a.get("operationId"):
        op = ctx.gen.ops[a["operationId"]]
        call_args = []
        if op.body_type:
            body_obj = params_obj(a.get("body"))
            call_args.append(f"{body_obj} as unknown as {op.body_type}")
        call_args.append(params_obj(a.get("params")))
        call_args.append("{ idempotencyKey: o.idempotencyKey }")
        after = bool(a.get("navigateTo"))
        body.append(f"this.run({ts_str(a['id'])}, {{")
        if a.get("confirm"):
            body.append(f"  confirm: {ts_str(a['confirm'])},")
        if a.get("successMessage"):
            body.append(f"  successMessage: {ts_str(a['successMessage'])},")
        body.append(f"  idempotent: {'true' if a.get('idempotent') else 'false'},")
        body.append(f"  call: (o) => this.api.{op.op_id}({', '.join(call_args)}),")
        if after:
            body.append(f"  after: () => this.go({link_ts_expr(ctx, a['navigateTo'], a.get('params'))}),")
        body.append("});")
    elif a.get("externalUrl"):
        url = a["externalUrl"]
        if "{" in url:
            ctx.imp("../../../shared/value/format", "interpolate")
            body.append(f"this.openExternal(interpolate({ts_str(url)}, item ?? this.current()));")
        else:
            body.append(f"this.openExternal({ts_str(url)});")
    elif a.get("navigateTo"):
        body.append(f"this.go({link_ts_expr(ctx, a['navigateTo'], a.get('params'))});")
    else:
        body.append("/* действие без эффекта в спеке */")
    uses_item = "item?." in "\n".join(body)
    if uses_item:
        body = [x.replace("item?.", "item.") for x in body]
        body.insert(0, "if (!item) return;")
    lines = [f"  protected {name}({item_arg}): void {{"] + ([] if uses_item else ["    void item;"]) + [f"    {b}" for b in body] + ["  }"]
    return "\n".join(lines)


def visible_expr(a: dict, var: str) -> str | None:
    vw = a.get("visibleWhen")
    if not vw:
        return None
    m = re.match(r"^([A-Za-z_][A-Za-z0-9_.]*) (==|!=) (.+)$", vw)
    if not m:
        return None
    f, op, val = m.groups()
    lit = val if re.fullmatch(r"-?\d+(\.\d+)?|true|false|null", val) else ts_str(val)
    return f"{field_expr(var, f)} {'===' if op == '==' else '!=='} {lit}"


def action_button(ctx: PageCtx, a: dict, var: str | None, compact: bool = False) -> str:
    name = camel("act-" + a["id"])
    sev = {"primary": "", "secondary": ' severity="secondary"', "danger": ' severity="danger"', "link": ' [text]="true"'}[a["kind"]]
    icon = f' icon="{a["icon"]}"' if a.get("icon") else ""
    arg = var or ""
    tid = f"{ctx.sid}-action-{a['id']}"
    if compact:
        btn = (f'<p-button{icon or " icon=\"pi pi-angle-right\""}{sev} [text]="true" [rounded]="true" ariaLabel="{attr(a["label"])}" pTooltip="{attr(a["label"])}"'
               f' (onClick)="$event.stopPropagation(); {name}({arg})" [loading]="running() === \'{a["id"]}\'" data-testid="{tid}" />')
    else:
        btn = (f'<p-button label="{attr(a["label"])}"{icon}{sev} (onClick)="{name}({arg})" [loading]="running() === \'{a["id"]}\'"'
               f' data-testid="{tid}" />')
    conds = []
    if a.get("roles"):
        conds.append("can([" + ", ".join(ts_str(r) for r in a["roles"]) + "])")
    if var:
        v = visible_expr(a, var)
        if v:
            conds.append(v)
    return f"@if ({' && '.join(conds)}) {{ {btn} }}" if conds else btn


def screen_actions(ctx: PageCtx, var: str | None) -> str:
    acts = [a for a in ctx.screen.get("actions", []) if a.get("scope", "screen") == "screen"]
    return "".join(action_button(ctx, a, var) for a in acts)


# ---------------------------------------------------------------- slots
def slot_tag(ctx: PageCtx, slot: dict, data_expr: str) -> str:
    cls = pascal(f"{ctx.sid}-{slot['id']}") + "Slot"
    file = f"{ctx.sid}-{slot['id']}.slot"
    ctx.slot_components.append((cls, file))
    ctx.imp(f"../../../slots/{file}", cls)
    return f'<slot-{ctx.sid}-{slot["id"]} [data]="{data_expr}" data-testid="{ctx.sid}-slot-{slot["id"]}" />'


def slots_at(ctx: PageCtx, placement: str, data_expr: str = "slotData()") -> str:
    return "\n".join(slot_tag(ctx, s, data_expr) for s in ctx.screen.get("slots", []) if s["placement"] == placement)


# ---------------------------------------------------------------- data sources
def add_sources(ctx: PageCtx, list_src: str | None = None) -> list[str]:
    """Loadable на каждый источник. list_src — источник, управляемый ListState."""
    ctx.imp("../../../shared/state/loadable", "loadable")
    data = ctx.screen.get("data") or {}
    sources = {"primary": data.get("primary")} | dict(data.get("secondary") or {})
    names = []
    for key, ds in sources.items():
        if not ds:
            continue
        op = ctx.gen.ops[ds["operationId"]]
        base = params_obj(ds.get("params"))
        if key == list_src:
            tab = ""
            if (ctx.screen.get("list") or {}).get("tabs"):
                tab = " ...TABS[this.list.tab()]?.params,"
            spread = "" if base == "{}" else f" ...{base},"
            call = (f"this.api.{op.op_id}({{{spread}{tab} ...(this.list.params() as unknown as Partial<{op.params_type}>) }})")
        else:
            call = f"this.api.{op.op_id}({base})"
        ctx.imp("../../api/api.service", op.params_type) if key == list_src else None
        ctx.members.append(f"  protected readonly {key} = loadable(() => {call});")
        names.append(key)
    refresh = [ds.get("refreshSeconds") for ds in sources.values() if ds and ds.get("refreshSeconds")]
    if refresh:
        # периодическое тихое обновление (data.*.refreshSeconds): минимальный интервал среди источников
        ctx.ctor.append(f"    const timer = setInterval(() => {{ if (this.allowed() && document.visibilityState !== 'hidden') this.reload(true); }}, {min(refresh) * 1000});")
        ctx.ctor.append("    this.destroyRef.onDestroy(() => clearInterval(timer));")
    reload = "\n".join(f"    this.{n}.load({{ silent }});" for n in names)
    ctx.members.append(f"  protected override reload(silent = false): void {{\n{reload}\n  }}")
    ctx.members.append("  protected readonly slotData = computed(() => ({ " + ", ".join(f"{n}: this.{n}.data()" for n in names) + " }));")
    ctx.imp("@angular/core", "computed")
    return names


def items_member(ctx: PageCtx, src: str) -> str:
    """Computed со списком элементов источника (Page|array|object → array)."""
    name = f"{src}Items"
    if any(m.startswith(f"  protected readonly {name} ") for m in ctx.members):
        return f"{name}()"
    op = ctx.source_op(src)
    if op and op.response_kind == "object":
        ctx.imp("../../../shared/screen/data-helpers", "asList")
        ctx.members.append(f"  protected readonly {name} = computed(() => asList(this.{src}.data()));")
    else:
        ctx.imp("../../../shared/screen/data-helpers", "itemsOf")
        ctx.members.append(f"  protected readonly {name} = computed(() => itemsOf(this.{src}.data()));")
    return f"{name}()"


def layer_ts(ctx: PageCtx, layer: dict, src_items_expr: str) -> str:
    ctx.imp("../../../shared/map/features", "toFeatures", "MapLayerData")
    opts = {"geometryField": layer["geometryField"]}
    for k in ("labelField", "colorBy"):
        if layer.get(k):
            opts[k] = layer[k]
    parts = [f"{k}: {ts_lit(v)}" for k, v in opts.items()]
    if layer.get("statusMap"):
        parts.append(f"statusMap: this.{ctx.status_map(layer['statusMap'])}")
    if layer.get("popupFields"):
        pf = []
        for f in layer["popupFields"]:
            item = f"{{ field: {ts_lit(f['field'])}, label: {ts_lit(f['label'])}, format: {ts_lit(f.get('format', 'text'))}"
            if f.get("statusMap"):
                item += f", statusMap: this.{ctx.status_map(f['statusMap'])}"
            pf.append(item + " }")
        parts.append("popupFields: [" + ", ".join(pf) + "]")
    feats = f"toFeatures(this.{src_items_expr}, {{ {', '.join(parts)} }})"
    if layer["kind"] == "line":
        ctx.imp("../../../shared/map/features", "pointsToLine")
        feats = f"pointsToLine({feats})"
    clickable = "true" if layer.get("linkTo") else "false"
    return f"{{ id: {ts_lit(layer['id'])}, kind: {ts_lit(layer['kind'])}, clickable: {clickable}, features: {feats} }}"


def feature_click_method(ctx: PageCtx, layers: list[dict]) -> str:
    cases = []
    for l in layers:
        if l.get("linkTo"):
            route = ctx.screen_by_id(l["linkTo"])["route"]
            segs = route_segments(route, lambda _n: "e.id")
            cases.append(f"      case {ts_lit(l['id'])}: this.go([{', '.join(segs)}]); break;")
    ctx.imp("../../../shared/map/app-map.component", "FeatureClick")
    body = "\n".join(cases) or "      default: break;"
    return f"  protected onFeatureClick(e: FeatureClick): void {{\n    switch (e.layerId) {{\n{body}\n    }}\n  }}"


# ---------------------------------------------------------------- realtime
def realtime_members(ctx: PageCtx, list_src: str | None = None) -> None:
    rt = ctx.screen.get("realtime")
    notes = ctx.screen.get("notifications", [])
    if notes:
        ctx.members.append("  protected override readonly notificationRules = " + ts_lit(
            [{"eventType": n["eventType"], "text": n["text"], "severity": n["severity"]} for n in notes]) + " as const;")
    if not rt:
        return
    ctx.members.append(f"  protected override readonly realtimeTypes = {ts_lit(rt['eventTypes'])};")
    mode = rt["mode"]
    if mode == "refresh":
        return
    ctx.imp("../../../core/realtime/event-envelope", "EventEnvelope", "envelopeToItem")
    lines = []
    if mode == "prepend":
        src = list_src or "primary"
        ctx.imp("../../../shared/screen/data-helpers", "prependToPage")
        guard = "if (this.list.page() !== 1 || this.list.hasFilters()) { this.scheduleRefresh(); return; }" if list_src else ""
        lines += [guard, f"this.{src}.update((p) => prependToPage(p, envelopeToItem(e), 50));"]
    elif mode == "patch":
        ctx.imp("../../../shared/screen/data-helpers", "patchInPage", "prependToPage")
        layers = (ctx.screen.get("map") or {}).get("layers", [])
        for l in layers:
            if l.get("realtimeUpdate"):
                lines.append(f"this.{l['source']}.update((p) => patchInPage(p, e.subject?.id, e.payload));")
        sp = (ctx.screen.get("map") or {}).get("sidePanel")
