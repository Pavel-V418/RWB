"""Backend-агент: реализует интерфейсы I<Tag>Api сгенерированного backend по контракту и требованиям.

    python -m specforge_backend.backend.agent <artifacts_dir> [--tags Zones,Sessions] [--force] [--max-attempts 3] [--dry-run]
                                   [--no-tests | --tests-only]

Контракт команды: run(input_dir, output_dir, llm) -> GateResult{passed, errors, tokens, attempts}.
  input_dir  — artifacts (02_system, 01_requirements, 04_backend после генераторов)
  output_dir — artifacts/04_backend

Цикл на каждый тег: контекст → LLM → dotnet build проекта Application → до N-1 попыток ремонта по ошибкам
компилятора → если не вышло, детерминированная заглушка (501), чтобы сборка оставалась зелёной.
Затем этап тестов (testgen.py): интеграционные тесты фичи по критериям приёмки → dotnet test её класса → ремонт тестов;
непрошедшие тесты получают Skip с причиной и делают шлюз красным (их текст — готовая обратная связь для --feedback).
Итог — 04_backend/backend-agent.json; ответы модели — 04_backend/.agent/ (для разбора, в git не попадают).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .context import APIS, JOBS_TAG, ContextBuilder, build_jobs, feature_namespace
from .llm import LlmClient, estimate_tokens
from .prompts import SYSTEM, jobs_prompt, repair_prompt, task_prompt
from . import testgen

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "generators"))
from gate_report import parse as parse_build_errors  # noqa: E402

FEATURES = "src/App.Application/Features"
REGISTRATIONS = "src/App.Application/DependencyInjection.Features.cs"
APPLICATION_PROJECT = "src/App.Application/App.Application.csproj"
CODE_BLOCK = re.compile(r"```(?:csharp|cs|c#)?\s*\n(.*?)```", re.DOTALL)


@dataclass
class GateResult:
    passed: bool
    errors: list[dict] = field(default_factory=list)
    tokens: int = 0
    attempts: int = 0
    tags: dict[str, str] = field(default_factory=dict)  # тег → implemented | stub | skipped
    tests: dict[str, dict] = field(default_factory=dict)  # тег → {status: passed | skipped_failures | no_tests, tests, failed}


def dotnet(args: list[str], cwd: Path) -> tuple[int, str]:
    """DOTNET из окружения позволяет собирать в контейнере (на vm5 нет SDK): см. agents/backend/README.md."""
    cmd = shlex.split(os.environ.get("DOTNET", "dotnet")) + args
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    return proc.returncode, proc.stdout + proc.stderr


def extract_code(answer: str) -> str | None:
    blocks = CODE_BLOCK.findall(answer)
    return max(blocks, key=len).strip() + "\n" if blocks else None


def write_registrations(backend: Path) -> None:
    """DI для всех реализаций I*Api в Features/ — детерминированно, без участия модели."""
    pairs = []
    for path in sorted((backend / FEATURES).rglob("*.cs")):
        text = path.read_text(encoding="utf-8")
        ns = re.search(r"^namespace ([\w.]+);", text, re.MULTILINE)
        for m in re.finditer(r"class\s+(\w+)\s*(?:\([^{;]*?\))?\s*:\s*(?:[\w.]+\.)?(I\w+Api|IScheduledJob)\b", text):
            pairs.append((m.group(2), f"{ns.group(1)}.{m.group(1)}" if ns else m.group(1)))
    lines = "\n".join(f"        services.AddScoped<{iface}, {impl}>();" for iface, impl in sorted(set(pairs)))
    usings = "using App.Application.Abstractions;\n" if any(i == "IScheduledJob" for i, _ in pairs) else ""
    (backend / REGISTRATIONS).write_text(f"""// <auto-generated>
// Сгенерировано agents/backend: регистрации реализаций I*Api из Features/.
// </auto-generated>
{usings}using App.Application.Contracts;
using Microsoft.Extensions.DependencyInjection;

namespace App.Application;

public static partial class DependencyInjection
{{
    static partial void AddApplicationServices(IServiceCollection services)
    {{
{lines}
    }}
}}
""", encoding="utf-8")


def stub(interface: str, tag: str, namespace: str | None = None) -> str:
    """Заглушка: все методы бросают FeatureNotImplementedException (HTTP 501). Сборка остаётся зелёной."""
    methods = []
    for m in re.finditer(r"^\s*((?:System\.Threading\.Tasks\.)?Task\S*\s+(\w+)\(.*\));$", interface, re.MULTILINE):
        methods.append(f"    public {m.group(1)} =>\n        throw new FeatureNotImplementedException(nameof({m.group(2)}));")
    body = "\n\n".join(methods)
    return f"""// Заглушка backend-агента: модель не справилась за отведённые попытки. Операции отвечают 501.
using App.Application.Common;
using App.Application.Contracts;

namespace {namespace or f"App.Application.Features.{tag}"};

internal sealed class {tag}Api : I{tag}Api
{{
{body}
}}
"""


JOBS_STUB = """// Заглушка backend-агента: фоновые задачи не собрались за отведённые попытки — таймеров нет.
namespace App.Application.Features.Jobs;
"""


def implemented_elsewhere(backend: Path, tag: str, own: Path) -> bool:
    for path in (backend / FEATURES).rglob("*.cs"):
        if path != own and re.search(rf":\s*(?:[\w.]+\.)?I{tag}Api\b", path.read_text(encoding="utf-8")):
            return True
    return False


# Шлюз безопасности: компилируется, но недопустимо. Срабатывает до сборки, ошибки уходят в ремонт как обычные.
FORBIDDEN = [
    (re.compile(r"\b(FromSqlRaw|ExecuteSqlRaw|ExecuteSqlRawAsync|SqlQueryRaw)\b"),
     "SEC001: {0} запрещён — SQL-инъекция. Используй FromSql($\"... {{параметр}} ...\") с интерполяцией: значения уходят параметрами."),
    (re.compile(r"\bDateTime(Offset)?\.(Now|UtcNow)\b"),
     "SEC002: {0} запрещён — время только из TimeProvider (time.GetUtcNow()), иначе не работает TIME_SCALE и тесты."),
]


def policy_errors(file: Path) -> list[dict]:
    errors = []
    for number, line in enumerate(file.read_text(encoding="utf-8").splitlines(), 1):
        for pattern, message in FORBIDDEN:
            if m := pattern.search(line):
                errors.append({"file": str(file), "line": number, "message": message.format(m.group(0))})
    return errors


def build_errors(backend: Path, file: Path) -> list[dict] | None:
    """None — собралось и прошло политику; иначе ошибки (сначала из файла агента)."""
    if policy := policy_errors(file):
        return policy
    code, log = dotnet(["build", APPLICATION_PROJECT, "-nologo", "-v", "q", "-clp:NoSummary", "-warnaserror"], backend)
    if code == 0:
        return None
    errors = parse_build_errors(log, backend) or [{"file": None, "line": None, "message": log.strip()[-2000:]}]
    own = [e for e in errors if e["file"] and Path(e["file"]).name == file.name]
    return own + [e for e in errors if e not in own]


def format_errors(errors: list[dict], limit: int = 25) -> str:
    return "\n".join(f"- {Path(e['file']).name if e['file'] else '?'}:{e['line']}: {e['message']}" for e in errors[:limit])


def run(input_dir: Path, output_dir: Path, llm: LlmClient | None, tags: list[str] | None = None,
        max_attempts: int = 3, force: bool = False, log=print, feedback: str | None = None,
        tests: bool = True, tests_only: bool = False) -> GateResult:
    """feedback — ошибка работающего кода (e2e, Schemathesis, лог): тег чинится от текущего файла, а не с нуля.
    Если исправление не собралось, текущий (собиравшийся) файл остаётся — заглушка не ставится.
    tests_only — только этап тестов для тегов (без реализации); tests=False — без этапа тестов."""
    builder = ContextBuilder(input_dir)
    backend = output_dir
    trace = backend / ".agent"
    trace.mkdir(exist_ok=True)
    (trace / ".gitignore").write_text("*\n", encoding="utf-8")
    interfaces = {name[1:-3]: block for name, block in builder.apis.items() if name.startswith("I") and name.endswith("Api")}
    result = GateResult(passed=True)

    for tag in [] if tests_only else tags or builder.tags() + [JOBS_TAG]:
        jobs = tag == JOBS_TAG
        file = backend / FEATURES / tag / ("ScheduledJobs.cs" if jobs else f"{tag}Api.cs")
        original = file.read_text(encoding="utf-8") if file.exists() else None
        if feedback and original is None:
            log(f"[{tag}] нет реализации для ремонта по обратной связи — пропускаю")
            result.tags[tag] = "skipped"
            continue
        if not feedback and ((not jobs and implemented_elsewhere(backend, tag, file))
                             or (original is not None and not force and "Заглушка backend-агента" not in original)):
            result.tags[tag] = "skipped"
            log(f"[{tag}] уже реализован — пропускаю (--force, чтобы перегенерировать)")
            continue

        context = build_jobs(builder).render() if jobs else builder.build(tag).render()
        prompt = jobs_prompt(context) if jobs else task_prompt(context, tag, feature_namespace(backend, tag))
        log(f"[{tag}] контекст ~{estimate_tokens(SYSTEM + prompt)} токенов")
        file.parent.mkdir(parents=True, exist_ok=True)
        code, errors = None, None
        if feedback:
            # Ремонт по поведению: стартуем с текущего кода и описания сбоя вместо ошибок компилятора
            code, errors = original, [{"file": str(file), "line": None, "message": "Ошибка при работе (не компиляции): " + feedback}]

        for attempt in range(1, max_attempts + 1):
            result.attempts += 1
            started = time.monotonic()
            user = prompt if code is None else repair_prompt(code, format_errors(errors or []), tag) + "\n\nКонтекст:\n" + context
            answer = llm.chat(SYSTEM, user)
            (trace / f"{tag}-{attempt}.md").write_text(answer, encoding="utf-8")
            new_code = extract_code(answer)
            if new_code is None:
                errors = [{"file": str(file), "line": None, "message": "ответ модели без блока ```csharp"}]
                log(f"[{tag}] попытка {attempt}: нет блока кода")
                continue
            code = new_code
            file.write_text(code, encoding="utf-8")
            write_registrations(backend)
            errors = build_errors(backend, file)
            (trace / f"{tag}-{attempt}.errors.txt").write_text(format_errors(errors or [], limit=100) or "OK\n", encoding="utf-8")
            log(f"[{tag}] попытка {attempt}: {'собрано' if errors is None else f'{len(errors)} ошибок'} "
                f"({time.monotonic() - started:.0f} с, всего токенов {llm.usage.total})")
            if errors is None:
                break

        if errors is None:
            result.tags[tag] = "repaired" if feedback else "implemented"
            continue
        result.passed = False
        if feedback and original is not None:
            file.write_text(original, encoding="utf-8")
            write_registrations(backend)
            result.tags[tag] = "unchanged"
            result.errors += [{**e, "tag": tag} for e in (errors or [])[:10]]
            log(f"[{tag}] исправление не собралось — оставлен прежний код")
            continue
        result.tags[tag] = "stub"
        result.errors += [{**e, "tag": tag} for e in (errors or [])[:10]]
        file.write_text(JOBS_STUB if jobs else stub(interfaces[tag], tag, feature_namespace(backend, tag)), encoding="utf-8")
        write_registrations(backend)
        log(f"[{tag}] не собрался за {max_attempts} попыток — заглушка 501")

    write_registrations(backend)
    if (tests or tests_only) and llm is not None:
        run_tests_stage(builder, backend, [t for t in (tags or builder.tags()) if t != JOBS_TAG], result, llm,
                        max_attempts, force or tests_only, trace, log)
    code, log_text = dotnet(["build", "App.slnx", "-nologo", "-v", "q", "-clp:NoSummary", "-warnaserror"], backend)
    if code != 0:
        result.passed = False
        result.errors += (parse_build_errors(log_text, backend) or [{"file": None, "line": None, "message": log_text[-2000:]}])[:20]
    result.tokens = llm.usage.total if llm else 0
    report = backend / "backend-agent.json"
    if tags and report.exists():
        # Прогон по части тегов: итоги остальных тегов из прошлого отчёта сохраняются
        previous = json.loads(report.read_text(encoding="utf-8"))
        result.tags = {**{k: v for k, v in previous.get("tags", {}).items() if k not in result.tags}, **result.tags}
        result.tests = {**{k: v for k, v in previous.get("tests", {}).items() if k not in result.tests}, **result.tests}
    report.write_text(json.dumps(asdict(result), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # Матрица «требование → API → код → тест» (детерминированно); не шлюз — её сбой не валит этап
    trace_matrix = subprocess.run([sys.executable, str(ROOT / "generators/docs/traceability.py"), str(backend.parent)],
                                  capture_output=True, text=True)
    log((trace_matrix.stdout or trace_matrix.stderr).strip()[-500:])
    return result


def has_tests(backend: Path, tag: str) -> bool:
    return any(re.search(rf"\bclass\s+{tag}ApiTests\b", p.read_text(encoding="utf-8"))
               for p in (backend / "tests").rglob("*.cs") if "/bin/" not in str(p) and "/obj/" not in str(p))


def run_tests_stage(builder: ContextBuilder, backend: Path, tags: list[str], result: GateResult, llm: LlmClient,
                    max_attempts: int, force: bool, trace: Path, log) -> None:
    """Тесты для тегов с настоящей реализацией. Уже существующие тесты не перегенерируются без force, но прогоняются."""
    for tag in tags:
        impl = backend / FEATURES / tag / f"{tag}Api.cs"
        if not impl.exists() or "Заглушка backend-агента" in impl.read_text(encoding="utf-8"):
            continue
        fresh = result.tags.get(tag) in ("implemented", "repaired")
        own_tests = backend / testgen.TESTS_DIR / f"{tag}ApiTests.cs"
        if has_tests(backend, tag) and not ((force or fresh) and own_tests.exists()):
            if not own_tests.exists():
                continue  # тесты написаны вручную (например, эталонный Auth) — не трогаем
            kind, failed = testgen.run_class(backend, tag, dotnet)
            report = {"status": "passed" if kind == "ok" else "failing", "tests": len(re.findall(r"\[Fact", own_tests.read_text(encoding="utf-8"))),
                      "failed": failed[:10], "attempts": 0}
            log(f"[{tag}:tests] существующие тесты: {report['status']}")
        else:
            report = testgen.generate(builder, backend, tag, llm, dotnet, extract_code, trace, max_attempts, log)
        result.tests[tag] = report
        if report["status"] != "passed":
            result.passed = False
            result.errors += [{"file": str(own_tests.relative_to(backend)), "line": None, "tag": tag,
                               "message": f"тест {f.get('test') or '?'}: {f['message'][:500]}"} for f in report["failed"][:10]]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("artifacts", type=Path)
    p.add_argument("--tags", help="через запятую; по умолчанию все I<Tag>Api")
    p.add_argument("--force", action="store_true", help="перегенерировать уже реализованные агентом теги")
    p.add_argument("--max-attempts", type=int, default=4)
    p.add_argument("--dry-run", action="store_true", help="без LLM: показать размер контекста и промпт первого тега")
    p.add_argument("--feedback", type=Path, help="файл с ошибкой работающего кода (e2e/лог) — ремонт тегов из --tags")
    p.add_argument("--no-tests", action="store_true", help="без этапа тестов")
    p.add_argument("--tests-only", action="store_true", help="только этап тестов (тесты перегенерируются)")
    a = p.parse_args()
    artifacts = a.artifacts.resolve()
    tags = a.tags.split(",") if a.tags else None

    if a.dry_run:
        builder = ContextBuilder(artifacts)

        def prompt_for(tag: str) -> str:
            return jobs_prompt(build_jobs(builder).render()) if tag == JOBS_TAG else task_prompt(builder.build(tag).render(), tag, feature_namespace(builder.backend, tag))

        selected = tags or builder.tags() + [JOBS_TAG]
        for tag in selected:
            print(f"{tag}: ~{estimate_tokens(SYSTEM + prompt_for(tag))} токенов")
        print("\n" + prompt_for(selected[0]))
        return

    feedback = a.feedback.read_text(encoding="utf-8").strip() if a.feedback else None
    if feedback and not tags:
        p.error("--feedback требует --tags: ремонт по поведению адресный")
    result = run(artifacts, artifacts / "04_backend", LlmClient.from_env(), tags, a.max_attempts, a.force, feedback=feedback,
                 tests=not a.no_tests, tests_only=a.tests_only)
    print(json.dumps({k: v for k, v in asdict(result).items() if k != "errors"}, ensure_ascii=False))
    sys.exit(0 if result.passed else 1)


if __name__ == "__main__":
    main()
