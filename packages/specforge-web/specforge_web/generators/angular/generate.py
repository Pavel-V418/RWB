def e2e_spec(spec: dict, gen=None) -> str:
    screens = [s for s in spec["screens"] if "/:" not in s["route"] and not s.get("public")]
    login = gen.ops.get("login") if gen else None
    api_cfg = json.dumps({"apiBase": "/api/v1", "loginPath": login.path if login else None}, ensure_ascii=False)
    live = [s for s in screens if (s.get("realtime") or {}).get("mode") == "prepend" and s["archetype"] == "timeline"]
    # JSON, а не склейка строк: пустой список должен давать [], а не «[ , ]» (дырка → падение всего файла тестов)
    live_items = json.dumps([{"id": s["id"], "route": s["route"]} for s in live], ensure_ascii=False)
    roles = sorted({r for s in screens for r in s["roles"]})
    items = json.dumps([{"id": s["id"], "route": s["route"]} for s in screens], ensure_ascii=False)
    return f"""// AUTO-GENERATED: обход экранов без параметров. Запуск против поднятого стенда (вход — e2e/support.ts) или mock-режима.
import {{ expect, test }} from '@playwright/test';

import {{ ApiCfg, signIn }} from './support';

const API: ApiCfg = {api_cfg};

const SCREENS: {{ id: string; route: string }}[] = {items};

test.beforeEach(async ({{ page, request }}) => {{
  const reason = await signIn(page, request, API, {ts_lit(roles)});
  test.skip(!!reason, reason ?? '');
}});

for (const s of SCREENS) {{
  test(`экран ${{s.id}} открывается без ошибок консоли`, async ({{ page }}) => {{
    const errors: string[] = [];
    page.on('pageerror', (e) => errors.push(e.message));
    page.on('console', (m) => m.type() === 'error' && !/tile|maplibre|404/i.test(m.text()) && errors.push(m.text()));
    await page.goto(s.route);
    await expect(page.getByTestId(s.id)).toBeVisible();
    await expect(page.locator(`[data-testid^="${{s.id}}-state-"]`).or(page.getByTestId(s.id))).toBeVisible();
    expect(errors).toEqual([]);
  }});
}}

// Realtime: в mock-режиме (MockRealtimeService) новые события должны появляться в ленте без перезагрузки.
const LIVE: {{ id: string; route: string }}[] = {live_items};
for (const s of LIVE) {{
  test(`лента ${{s.id}} получает события в реальном времени`, async ({{ page }}) => {{
    test.skip(!process.env['E2E_REALTIME'], 'запуск: E2E_REALTIME=1 против ng serve --configuration mock');
    await page.goto(s.route);
    const items = page.getByTestId(`${{s.id}}-timeline-item`);
    const before = await items.count();
    await expect.poll(async () => items.count(), {{ timeout: 20_000 }}).toBeGreaterThan(before);
  }});
}}
"""


# ---------------------------------------------------------------- main
def generate(spec: dict, openapi: dict, out: Path, events: list | None = None) -> dict:
    app = spec["app"]
    if app["platform"] != "web":
        raise SystemExit("Генератор Angular принимает только app.platform=web")
    manifest = json.loads((DESIGN / "kit-manifest.json").read_text(encoding="utf-8"))
    report = {"files": [], "generatedLines": 0, "pages": [], "slots": [], "scaffoldLines": 0}

    # 1. каркас (не трогаем существующие slots/ и node_modules)
    out.mkdir(parents=True, exist_ok=True)
    for src in SCAFFOLD.rglob("*"):
        rel = src.relative_to(SCAFFOLD)
        if src.is_dir() or "node_modules" in rel.parts or rel.parts[:3] == ("src", "app", "slots"):
            continue
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        if src.suffix in (".ts", ".html", ".scss"):
            report["scaffoldLines"] += src.read_text(encoding="utf-8").count("\n")
    gen_dir = out / "src" / "app" / "generated"
    if gen_dir.exists():
        shutil.rmtree(gen_dir)
    # 2. дизайн-система + инструменты гейта
    (out / "src" / "styles").mkdir(parents=True, exist_ok=True)
    shutil.copy2(DESIGN / "tokens.scss", out / "src" / "styles" / "tokens.scss")
    shutil.copy2(DESIGN / "layout.scss", out / "src" / "styles" / "layout.scss")
    shutil.copy2(DESIGN / "preset.ts", out / "src" / "app" / "preset.ts")
    (out / "tools").mkdir(exist_ok=True)
    shutil.copy2(DESIGN / "kit-manifest.json", out / "tools" / "kit-manifest.json")
    shutil.copy2(ROOT / "tools" / "kit_lint.py", out / "tools" / "kit_lint.py")
    (out / "openapi.yaml").write_text(yaml.safe_dump(openapi, allow_unicode=True, sort_keys=False), encoding="utf-8")
    if events is not None:
        (out / "src" / "assets" / "mock-events.json").write_text(json.dumps(events, ensure_ascii=False, indent=2), encoding="utf-8")

    # 3. API
    gen = TsGen(openapi)
    write(gen_dir / "api" / "models.ts", gen.models_ts(), report)
    write(gen_dir / "api" / "api.service.ts", gen.service_ts(), report)

    # 4. страницы
    screens = spec["screens"]
    home = next((s["route"] for s in screens if s["route"] == "/"), None) or next(
        (next(s for s in screens if s["id"] == n["screen"])["route"] for n in spec["navigation"]), "/")
    app["_home"] = home
    kit_tags = [c["tag"] for c in manifest["components"] if not c.get("deprecatedInProject")]
    public_routes, private_routes = [], []
    for s in screens:
        sid, cls = s["id"], pascal(s["id"]) + "Page"
        pdir = gen_dir / "pages" / sid
        public = s["archetype"] in ("login", "forbidden")
        if s["archetype"] == "login":
            ts, html = login_page(app, s)
            slots = []
        elif s["archetype"] == "forbidden":
            ts, html = forbidden_page(app, s, spec)
            slots = []
        else:
            page = build_page(app, s, spec, gen, manifest)
            ts, html, slots = page["ts"], page["html"], page["slots"]
        write(pdir / f"{sid}.page.ts", ts, report)
        write(pdir / f"{sid}.page.html", html, report)
        write(pdir / f"{sid}.page.spec.ts", page_spec(s, cls, public), report)
        path = s["route"].lstrip("/")
        pm = " pathMatch: 'full'," if path == '' else ''
        entry = (f"  {{ path: {ts_str(path)},{pm} title: {ts_str(s['title'] + ' · ' + app['title'])}, data: {{ roles: {ts_lit(s['roles'])}, screen: {ts_str(sid)} }},"
                 f" loadComponent: () => import('./pages/{sid}/{sid}.page').then((m) => m.{cls}) }},")
        (public_routes if public or s.get("public") else private_routes).append((path, entry))
        report["pages"].append({"id": sid, "archetype": s["archetype"], "route": s["route"]})
        for slot_cls, file in slots:
            slot = next(x for x in s.get("slots", []) if f"{sid}-{x['id']}.slot" == file)
            spath = out / "src" / "app" / "slots" / f"{file}.ts"
            if not spath.exists():
                write(spath, slot_stub(slot_cls, file, s, slot, kit_tags), report)
            implemented = SLOT_STUB_MARK not in spath.read_text(encoding="utf-8")
            report["slots"].append({"screen": sid, "slot": slot["id"], "file": str(spath.relative_to(out)), "class": slot_cls,
                                    "task": slot["task"], "components": slot.get("components") or [],
                                    "requirements": slot.get("requirements", []), "implemented": implemented})

    # статические маршруты раньше параметрических (/things/new раньше /things/:id)
    def order(item):
        path = item[0]
        return (path.count("/"), ":" in path, path)
    private_routes.sort(key=order)
    routes_ts = ["// AUTO-GENERATED by SpecForge. Не редактировать.", "import { Routes } from '@angular/router';", "",
                 "export const PUBLIC_ROUTES: Routes = [", *[e for _, e in public_routes], "];", "",
                 "export const GENERATED_ROUTES: Routes = [", *[e for _, e in private_routes], "];", ""]
    write(gen_dir / "routes.ts", "\n".join(routes_ts), report)

    by_id = {s["id"]: s for s in screens}
    nav = [{"screen": n["screen"], "label": n["label"], "icon": n.get("icon", "pi pi-circle"), "path": by_id[n["screen"]]["route"],
            "roles": by_id[n["screen"]]["roles"]} for n in spec["navigation"]]
    write(gen_dir / "navigation.ts",
          "// AUTO-GENERATED by SpecForge.\nexport interface NavItem { screen: string; label: string; icon: string; path: string; roles: string[]; }\n\n"
          f"export const NAVIGATION: NavItem[] = {json.dumps(nav, ensure_ascii=False, indent=2)};\n", report)
    write(gen_dir / "app-meta.ts",
          f"// AUTO-GENERATED by SpecForge.\nexport const APP_META = {{ id: {ts_str(app['id'])}, title: {ts_str(app['title'])}, home: {ts_str(home)}, authRequired: {'true' if (app.get('auth') or {}).get('required', True) else 'false'} }} as const;\n", report)

    # 5. витрина UI Kit и e2e
    sc_ts, sc_html = showcase_component(manifest)
    kdir = out / "src" / "app" / "pages" / "kit-showcase"
    write(kdir / "kit-showcase.component.ts", sc_ts, report)
    write(kdir / "kit-showcase.component.html", sc_html, report)
    write(out / "e2e" / "screens.spec.ts", e2e_spec(spec, gen), report)
    sc_cfg = build_scenarios(spec, gen)
    write(out / "e2e" / "scenarios.spec.ts", scenarios_spec(spec, gen, sc_cfg), report)
    # требование → пользовательские сценарии (для матрицы трассируемости tools/ui_docs.py)
    write(out / "e2e" / "scenarios.trace.json", json.dumps({"generator": "scenarios", "requirements": scenario_trace(sc_cfg),
                                                             "skipped": sc_cfg["skipped"]}, ensure_ascii=False, indent=2) + "\n", report,
          deterministic=False)  # данные, не код: в долю детерминированного кода не входят

    report["slotsTotal"] = len(report["slots"])
    report["slotsImplemented"] = sum(1 for s in report["slots"] if s["implemented"])
    (out / "slots.json").write_text(json.dumps(report["slots"], ensure_ascii=False, indent=2), encoding="utf-8")
    summary = {k: v for k, v in report.items() if k != "files"}
    summary["filesWritten"] = len(report["files"])
    (out / "generation-report.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="SpecForge Angular generator")
    ap.add_argument("--spec", type=Path, required=True)
    ap.add_argument("--openapi", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--events", type=Path)
    a = ap.parse_args(argv)
    spec = json.loads(a.spec.read_text(encoding="utf-8"))
    openapi = yaml.safe_load(a.openapi.read_text(encoding="utf-8"))
    events = json.loads(a.events.read_text(encoding="utf-8")) if a.events else None
    summary = generate(spec, openapi, a.out, events)
    print(json.dumps({k: summary[k] for k in ("pages", "generatedLines", "scaffoldLines", "slotsTotal", "filesWritten")}, ensure_ascii=False)[:600])
    return 0


if __name__ == "__main__":
    sys.exit(main())
