"""Детерминированная генерация серверного контракта ASP.NET из OpenAPI 3.1 (без LLM).

    python gen_aspnet.py <openapi.yaml> <skeleton_dir>

Пишет в золотой каркас:
  src/App.Application/Contracts/Generated/Models.cs   — DTO (records) и enum'ы
  src/App.Application/Contracts/Generated/Apis.cs     — интерфейсы I<Tag>Api, их реализует backend-агент
  src/App.Api/Controllers/Generated/<Tag>Controller.cs — контроллеры: маршруты, роли, валидация, коды ответов

Соглашения контракта:
  - роли операции — x-roles ([] — анонимно), иначе security: [{bearerAuth: [admin]}];
  - x-idempotent: true или заголовок Idempotency-Key → атрибут [Idempotent] каркаса;
  - ошибки не описываются в сигнатурах: реализация бросает исключения каркаса (→ RFC 9457).
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

HEADER = "// <auto-generated>\n// Сгенерировано generators/server/gen_aspnet.py из OpenAPI. Не редактировать вручную.\n// </auto-generated>\n#nullable enable\n"

# Схемы, которые каркас уже реализует сам или которые маппятся на готовые типы
SKIPPED_SCHEMAS = {"Problem", "ValidationProblem"}
TYPE_MAPPINGS = {"GeoJsonGeometry": "NetTopologySuite.Geometries.Geometry"}
IDEMPOTENCY_HEADER = "Idempotency-Key"
# Как разные авторы контракта помечают анонимный доступ в x-roles
ANONYMOUS_ROLES = {"anonymous", "public", "guest", "*", "all"}

CS_KEYWORDS = {
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
    "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
    "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
    "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
    "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
    "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
    "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
}
# Суффикс DTO: сущности EF (App.Domain.Entities) называются по таблицам и совпали бы с именами схем
DTO_SUFFIX = "Dto"

VALUE_TYPES = {"int", "long", "double", "bool", "System.Guid", "System.DateTimeOffset", "System.DateOnly"}


def base_name(owner: str) -> str:
    """Имя владельца без суффикса DTO — для имён вложенных типов (RouteFeatureDto.properties → RouteFeatureProperties)."""
    return owner[: -len(DTO_SUFFIX)] if owner.endswith(DTO_SUFFIX) else owner


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(name: str) -> str:
    p = pascal(name)
    ident = p[:1].lower() + p[1:]
    return "@" + ident if ident in CS_KEYWORDS else ident


def xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").strip()


def summary(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = [xml(line) for line in text.strip().splitlines() if line.strip()]
    return [f"{indent}/// <summary>"] + [f"{indent}/// {line}" for line in lines] + [f"{indent}/// </summary>"]


def verbatim(s: str) -> str:
    return '@"' + s.replace('"', '""') + '"'


@dataclass
class CsType:
    name: str
    nullable: bool = False
    schema: dict = field(default_factory=dict)  # итоговая схема с ограничениями (после разворачивания $ref)

    @property
    def is_value(self) -> bool:
        return self.name in VALUE_TYPES or self.name in ENUMS

    def render(self) -> str:
        return self.name + ("?" if self.nullable else "")


ENUMS: dict[str, list[str]] = {}  # имя C# enum → значения


class Generator:
    def __init__(self, spec: dict):
        self.spec = spec
        self.schemas: dict = spec.get("components", {}).get("schemas", {})
        self.models: dict[str, list[str]] = {}  # имя → строки кода (порядок вставки детерминирован)
        self.parameters: dict = spec.get("components", {}).get("parameters", {})

    # ---------- типы ----------

    def ref_name(self, ref: str) -> str:
        return ref.rsplit("/", 1)[-1]

    def resolve(self, schema: dict) -> dict:
        while "$ref" in schema:
            schema = self.schemas[self.ref_name(schema["$ref"])]
        return schema

    def cs_type(self, schema: dict, owner: str, prop: str) -> CsType:
        """Тип C# для схемы свойства/параметра. Nullable учитывает только явный null в схеме."""
        nullable = False
        if "oneOf" in schema or "anyOf" in schema:
            variants = schema.get("oneOf") or schema.get("anyOf")
            non_null = [v for v in variants if v.get("type") != "null"]
            if len(non_null) != 1:
                # Полиморфизм без дискриминатора — отдаём как есть, JSON-деревом (реализация разберёт сама)
                return CsType("System.Text.Json.JsonElement", len(non_null) != len(variants), schema)
            nullable = len(non_null) != len(variants)
            inner = self.cs_type(non_null[0], owner, prop)
            return CsType(inner.name, nullable or inner.nullable, inner.schema)

        if "allOf" in schema and len(schema["allOf"]) == 1:
            # allOf из одной ссылки — способ добавить description к $ref (так пишет модель-архитектор)
            merged = {**schema["allOf"][0], **{k: v for k, v in schema.items() if k != "allOf"}}
            return self.cs_type(merged, owner, prop)

        if "$ref" in schema:
            name = self.ref_name(schema["$ref"])
            if name in TYPE_MAPPINGS:
                return CsType(TYPE_MAPPINGS[name], False, schema)
            target = self.schemas[name]
            if geo := self.geojson_type(target):
                return CsType(geo, False, schema)
            if self.is_named_type(target):
                self.ensure_model(name)
                cs_name = name if "enum" in target else name + DTO_SUFFIX
                return CsType(cs_name, False, {**target, **{k: v for k, v in schema.items() if k != "$ref"}})
            # именованный примитив (CityCode, PlateNumber) — подставляем с ограничениями
            return self.cs_type({**target, **{k: v for k, v in schema.items() if k != "$ref"}}, owner, prop)

        types = schema.get("type")
        if isinstance(types, list):
            nullable = "null" in types
            non_null = [t for t in types if t != "null"]
            types = non_null[0] if len(non_null) == 1 else None
        if types is None and not schema:
            return CsType("System.Text.Json.JsonElement", nullable, schema)

        fmt = schema.get("format")
        if types == "string":
            if "enum" in schema:
                enum_name = pascal(base_name(owner)) + pascal(prop)
                self.add_enum(enum_name, schema["enum"], schema.get("description"))
                return CsType(enum_name, nullable, schema)
            name = {"uuid": "System.Guid", "date-time": "System.DateTimeOffset", "date": "System.DateOnly"}.get(fmt, "string")
            return CsType(name, nullable, schema)
        if types == "integer":
            return CsType("long" if fmt == "int64" else "int", nullable, schema)
        if types == "number":
            return CsType("double", nullable, schema)
        if types == "boolean":
            return CsType("bool", nullable, schema)
        if types == "array":
            if "items" not in schema:
                # prefixItems (кортеж, например [lon, lat]): общий тип элементов, иначе JsonElement
                prefix = [self.cs_type(i, owner, prop + "Item").render() for i in schema.get("prefixItems", [])]
                item_type = prefix[0] if prefix and len(set(prefix)) == 1 else "System.Text.Json.JsonElement"
                return CsType(f"System.Collections.Generic.IReadOnlyList<{item_type}>", nullable, schema)
            item = self.cs_type(schema["items"], owner, prop + "Item")
            return CsType(f"System.Collections.Generic.IReadOnlyList<{item.render()}>", nullable, schema)
        if types == "object":
            if "properties" in schema:
                nested = pascal(base_name(owner)) + pascal(prop) + DTO_SUFFIX
                self.build_model(nested, schema)
                return CsType(nested, nullable, schema)
            return CsType("System.Text.Json.Nodes.JsonObject", nullable, schema)
        raise ValueError(f"{owner}.{prop}: неподдерживаемая схема {schema}")

    @staticmethod
    def geojson_type(schema: dict) -> str | None:
        """Схема вида {type, coordinates|geometries} — геометрия GeoJSON → тип NetTopologySuite."""
        props = schema.get("properties", {})
        if schema.get("type") != "object" or "type" not in props or not ({"coordinates", "geometries"} & set(props)):
            return None
        t = props["type"]
        kinds = [t["const"]] if "const" in t else t.get("enum", [])
        known = {"Point", "LineString", "Polygon", "MultiPoint", "MultiLineString", "MultiPolygon", "GeometryCollection"}
        kind = kinds[0] if len(kinds) == 1 and kinds[0] in known else "Geometry"
        return f"NetTopologySuite.Geometries.{kind}"

    def is_named_type(self, schema: dict) -> bool:
        return schema.get("type") == "object" or "allOf" in schema or "enum" in schema

    # ---------- модели ----------

    def add_enum(self, name: str, values: list, description: str | None) -> None:
        if name in ENUMS:
            return
        ENUMS[name] = values
        lines = summary(description, "")
        lines.append("[System.Text.Json.Serialization.JsonConverter(typeof(System.Text.Json.Serialization.JsonStringEnumConverter))]")
        lines.append(f"public enum {name}")
        lines.append("{")
        for v in values:
            lines.append(f'    [System.Text.Json.Serialization.JsonStringEnumMemberName("{v}")]')
            lines.append(f"    {pascal(str(v))},")
        lines.append("}")
        self.models[name] = lines

    def ensure_model(self, name: str) -> None:
        if name in self.models or name + DTO_SUFFIX in self.models or name in SKIPPED_SCHEMAS or name in TYPE_MAPPINGS:
            return
        schema = self.schemas[name]
        if "enum" in schema:
            self.add_enum(name, schema["enum"], schema.get("description"))
        else:
            self.build_model(name + DTO_SUFFIX, schema)

    def flatten(self, schema: dict) -> tuple[dict, list, str | None]:
        """allOf разворачивается в плоский набор свойств (наследование DTO не нужно)."""
        if "allOf" not in schema:
            return dict(schema.get("properties", {})), list(schema.get("required", [])), schema.get("description")
        props, required, desc = {}, [], schema.get("description")
        for part in schema["allOf"]:
            part = self.resolve(part)
            p, r, d = self.flatten(part)
            props.update(p)
            required += r
            desc = desc or d
        return props, required, desc

    def build_model(self, name: str, schema: dict) -> None:
        if name in self.models:
            return
        self.models[name] = []  # защита от рекурсии
        props, required, desc = self.flatten(schema)
        lines = summary(desc, "")
        lines.append(f"public sealed record {name}")
        lines.append("{")
        first = True
        for prop, prop_schema in props.items():
            t = self.cs_type(prop_schema, name, prop)
            is_required = prop in required
            const = prop_schema.get("const")
            default = prop_schema.get("default", self.resolve(prop_schema).get("default") if "$ref" in prop_schema else None)
            if not is_required and default is None and const is None:
                t.nullable = True
            if not first:
                lines.append("")
            first = False
            lines += summary(prop_schema.get("description"), "    ")
            lines += [f"    {a}" for a in self.validation(t)]
            lines.append(f'    [System.Text.Json.Serialization.JsonPropertyName("{prop}")]')
            prop_name = pascal(prop)
            if prop_name == name:
                prop_name += "Value"
            if const is not None:
                lines.append(f'    public string {prop_name} {{ get; init; }} = "{const}";')
            elif default is not None and not is_required:
                lines.append(f"    public {t.render()} {prop_name} {{ get; init; }} = {self.literal(t, default)};")
            else:
                req = "required " if is_required else ""
                lines.append(f"    public {req}{t.render()} {prop_name} {{ get; init; }}")
        lines.append("}")
        self.models[name] = lines

    def literal(self, t: CsType, value) -> str:
        if t.name in ENUMS:
            return f"global::App.Application.Contracts.{t.name}.{pascal(str(value))}"
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, (int, float)):
            return str(value) + ("d" if t.name == "double" else "")
        return '"' + str(value).replace('"', '\\"') + '"'

    def validation(self, t: CsType) -> list[str]:
        s = t.schema
        attrs = []
        if t.name == "string":
            mn, mx = s.get("minLength"), s.get("maxLength")
            if mx is not None:
                attrs.append(f"[System.ComponentModel.DataAnnotations.StringLength({mx}" + (f", MinimumLength = {mn})]" if mn else ")]"))
            elif mn is not None:
                attrs.append(f"[System.ComponentModel.DataAnnotations.MinLength({mn})]")
            if "pattern" in s:
                attrs.append(f"[System.ComponentModel.DataAnnotations.RegularExpression({verbatim(s['pattern'])})]")
        elif t.name in ("int", "long", "double"):
            lo = s.get("minimum", s.get("exclusiveMinimum"))
            hi = s.get("maximum", s.get("exclusiveMaximum"))
            if lo is not None or hi is not None:
                if t.name == "double":
                    lo_s = f"{float(lo)}d" if lo is not None else "double.MinValue"
                    hi_s = f"{float(hi)}d" if hi is not None else "double.MaxValue"
                else:
                    kind = "int" if t.name == "int" else "long"
                    lo_s = str(lo) if lo is not None else f"{kind}.MinValue"
                    hi_s = str(hi) if hi is not None else f"{kind}.MaxValue"
                    if t.name == "long":
                        lo_s, hi_s = f"(double){lo_s}", f"(double){hi_s}"
                extra = []
                if "exclusiveMinimum" in s:
                    extra.append("MinimumIsExclusive = true")
                if "exclusiveMaximum" in s:
                    extra.append("MaximumIsExclusive = true")
                attrs.append(f"[System.ComponentModel.DataAnnotations.Range({lo_s}, {hi_s}" + "".join(", " + e for e in extra) + ")]")
        elif t.name.startswith("System.Collections.Generic.IReadOnlyList"):
            if "minItems" in s:
                attrs.append(f"[System.ComponentModel.DataAnnotations.MinLength({s['minItems']})]")
            if "maxItems" in s:
                attrs.append(f"[System.ComponentModel.DataAnnotations.MaxLength({s['maxItems']})]")
        return attrs

    # ---------- операции ----------

    def operations(self):
        for path, item in self.spec["paths"].items():
            common = item.get("parameters", [])
            for method in ("get", "post", "put", "patch", "delete"):
                if method in item:
                    yield path, method, item[method], common

    def param(self, p: dict) -> dict:
        return self.parameters[self.ref_name(p["$ref"])] if "$ref" in p else p

    def render_apis(self) -> tuple[str, dict[str, list[str]]]:
        api_lines: dict[str, list[str]] = {}
        controllers: dict[str, list[str]] = {}
        global_security = self.spec.get("security", [])
        # «Все роли» — объединение x-roles контракта: такой операции достаточно аутентификации
        all_roles = {r for _, _, op, _ in self.operations() for r in op.get("x-roles", [])} - ANONYMOUS_ROLES

        for path, method, op, common in self.operations():
            tag = pascal((op.get("tags") or ["Default"])[0])
            op_id = pascal(op["operationId"])
            # (name, in) уникальны по OAS: параметр операции перекрывает общий, повтор в операции — последний
            # (живой архитектор дублирует page/pageSize — inline и через $ref); позиция — первого вхождения
            params_by_key: dict[tuple[str, str], dict] = {}
            for p in map(self.param, common + op.get("parameters", [])):
                params_by_key[(p["name"], p["in"])] = p
            params = list(params_by_key.values())
            security = op.get("security", global_security)
            roles = sorted({r for req in security for scopes in req.values() for r in scopes})
            anonymous = security == []
            if "x-roles" in op:
                # x-roles (соглашение команды) главнее: [] — анонимно; все роли сразу — любой аутентифицированный
                x_roles = set(op["x-roles"])
                anonymous = not x_roles or bool(x_roles & ANONYMOUS_ROLES)
                roles = [] if anonymous or x_roles >= all_roles else sorted(x_roles)

            # сигнатура
            args = []  # (есть значение по умолчанию, аргумент интерфейса, аргумент действия, имя)
            idempotent = False
            route = path.lstrip("/")
            for p in params:
                if p["in"] == "header" and p["name"] == IDEMPOTENCY_HEADER:
                    # GET безопасен по HTTP — ключ идемпотентности на чтении игнорируем (ошибка контракта, не требуем)
                    idempotent = method != "get"
                    continue
                t = self.cs_type(p.get("schema", {}), op_id, p["name"])
                required = p.get("required", False) or p["in"] == "path"
                default = p.get("schema", {}).get("default")
                ident = camel(p["name"])
                if p["in"] == "path":
                    constraint = {"System.Guid": "guid", "int": "int", "long": "long"}.get(t.name)
                    if constraint:
                        route = route.replace("{" + p["name"] + "}", "{" + p["name"] + ":" + constraint + "}")
                    binding = f'[Microsoft.AspNetCore.Mvc.FromRoute(Name = "{p["name"]}")]'
                elif p["in"] == "query":
                    required_attr = ", Microsoft.AspNetCore.Mvc.ModelBinding.BindRequired" if required else ""
                    binding = f'[Microsoft.AspNetCore.Mvc.FromQuery(Name = "{p["name"]}"){required_attr}]'
                elif p["in"] == "header":
                    binding = f'[Microsoft.AspNetCore.Mvc.FromHeader(Name = "{p["name"]}")]'
                else:
                    raise ValueError(f"{op_id}: параметр в {p['in']} не поддерживается")
                if not required and default is None:
                    t.nullable = True
                validation = "".join(" " + a for a in self.validation(t))
                suffix = f" = {self.literal(t, default)}" if default is not None and not required else ""
                args.append((bool(suffix), f"{t.render()} {ident}", f"{binding}{validation} {t.render()} {ident}{suffix}", ident))

            idempotent = idempotent or bool(op.get("x-idempotent"))

            body = op.get("requestBody")
            if body:
                schema = body["content"]["application/json"]["schema"]
                t = self.cs_type(schema, op_id, "Request")
                args.append((False, f"{t.render()} body", f"[Microsoft.AspNetCore.Mvc.FromBody] {t.render()} body", "body"))

            # C# требует необязательные параметры в конце; сортировка стабильна — порядок из контракта сохраняется
            args.sort(key=lambda a: a[0])
            iface_args = [a[1] for a in args] + ["System.Threading.CancellationToken cancellationToken"]
            action_args = [a[2] for a in args] + ["System.Threading.CancellationToken cancellationToken = default"]
            call_args = [a[3] for a in args] + ["cancellationToken"]

            # ответы
            responses = op.get("responses", {})
            success = sorted(c for c in responses if c.startswith("2"))
            result_type, content_type = None, None
            for code in success:
                content = self.resolve_response(responses[code]).get("content")
                if content:
                    content_type, media = next(iter(content.items()))
                    result_type = self.cs_type(media["schema"], op_id, "Response")
            has_no_content = "204" in success
            created = "201" in success

            if result_type is None:
                iface_ret, action_ret = "System.Threading.Tasks.Task", "Microsoft.AspNetCore.Mvc.IActionResult"
            elif has_no_content:
                iface_ret = f"System.Threading.Tasks.Task<{result_type.name}?>"
                action_ret = f"Microsoft.AspNetCore.Mvc.ActionResult<{result_type.name}>"
            else:
                iface_ret = f"System.Threading.Tasks.Task<{result_type.name}>"
                action_ret = f"Microsoft.AspNetCore.Mvc.ActionResult<{result_type.name}>"

            # интерфейс
            doc = summary(op.get("summary"), "    ")
            if has_no_content and result_type is not None:
                doc.insert(-1, "    /// Возврат null означает ответ 204 No Content.")
            api_lines.setdefault(tag, [])
            if api_lines[tag]:
                api_lines[tag].append("")
            api_lines[tag] += doc
            api_lines[tag].append(f"    {iface_ret} {op_id}Async({', '.join(iface_args)});")

            # действие контроллера
            c = controllers.setdefault(tag, [])
            if c:
                c.append("")
            c += summary(op.get("summary"), "    ")
            c.append(f'    [Microsoft.AspNetCore.Mvc.Http{pascal(method)}("{route}", Name = "{op["operationId"]}")]')
            if anonymous:
                c.append("    [Microsoft.AspNetCore.Authorization.AllowAnonymous]")
            if roles:
                # Roles, а не Policy: набор ролей задаёт контракт (driver, dispatcher, admin…), политики заводить не нужно
                c.append(f'    [Microsoft.AspNetCore.Authorization.Authorize(Roles = "{",".join(roles)}")]')
            if idempotent:
                c.append("    [App.Api.Idempotency.Idempotent]")
            for code in sorted(responses):
                status = int(code)
                if code.startswith("2") and result_type is not None and code != "204":
                    ct = f', "{content_type}"' if content_type and content_type != "application/json" else ""
                    c.append(f"    [Microsoft.AspNetCore.Mvc.ProducesResponseType<{result_type.name}>({status}{ct})]")
                elif code.startswith("2"):
                    c.append(f"    [Microsoft.AspNetCore.Mvc.ProducesResponseType({status})]")
                else:
                    c.append(f'    [Microsoft.AspNetCore.Mvc.ProducesResponseType<Microsoft.AspNetCore.Mvc.ProblemDetails>({status}, "application/problem+json")]')
            c.append(f"    public async System.Threading.Tasks.Task<{action_ret}> {op_id}(")
            c.append("        " + ",\n        ".join(action_args) + ")")
            c.append("    {")
            call = f"api.{op_id}Async({', '.join(call_args)})"
            if result_type is None:
                c.append(f"        await {call};")
                c.append("        return NoContent();" if has_no_content else f"        return StatusCode({success[0]});")
            elif has_no_content:
                c.append(f"        var result = await {call};")
                c.append("        return result is null ? NoContent() : Ok(result);")
            elif content_type and content_type != "application/json":
                # Нестандартный тип (например application/geo+json) — только у успешного ответа;
                # [Produces] на действии перебил бы и application/problem+json у ошибок
                status = 201 if created else 200
                c.append(f"        return new Microsoft.AspNetCore.Mvc.ObjectResult(await {call})")
                c.append("        {")
                c.append(f"            StatusCode = {status},")
                c.append(f'            ContentTypes = {{ "{content_type}" }},')
                c.append("        };")
            elif created:
                c.append(f"        return StatusCode(201, await {call});")
            else:
                c.append(f"        return Ok(await {call});")
            c.append("    }")

        apis = [HEADER, "namespace App.Application.Contracts;", ""]
        for i, (tag, lines) in enumerate(api_lines.items()):
            if i:
                apis.append("")
            apis += [
                f"/// <summary>Операции тега {tag}. Реализует backend-агент; ошибки — исключения App.Application.Common.</summary>",
                f"public interface I{tag}Api",
                "{",
                *lines,
                "}",
            ]

        files = {}
        for tag, lines in controllers.items():
            files[f"{tag}Controller.cs"] = "\n".join([
                HEADER + "using App.Application.Contracts;",
                "",
                "namespace App.Api.Controllers.Generated;",
                "",
                "[Microsoft.AspNetCore.Mvc.ApiController]",
                f'[Microsoft.AspNetCore.Http.Tags("{tag}")]',
                f"public sealed class {tag}Controller(I{tag}Api api) : Microsoft.AspNetCore.Mvc.ControllerBase",
                "{",
                *lines,
                "}",
                "",
            ])
        return "\n".join(apis) + "\n", files

    def resolve_response(self, response: dict) -> dict:
        if "$ref" in response:
            return self.spec["components"]["responses"][self.ref_name(response["$ref"])]
        return response

    def render_roles(self) -> str:
        """Константы ролей контракта (x-roles и scopes в security) — partial к Roles каркаса, где уже есть Admin."""
        roles = {r for _, _, op, _ in self.operations() for r in op.get("x-roles", [])}
        for req in self.spec.get("security", []) + [r for _, _, op, _ in self.operations() for r in op.get("security", [])]:
            roles.update(scope for scopes in req.values() for scope in scopes)
        roles -= ANONYMOUS_ROLES | {"admin"}
        lines = [HEADER.rstrip("\n"), "namespace App.Application.Common;", "",
                 "public static partial class Roles", "{"]
        lines += [f'    public const string {pascal(r)} = "{r}";' for r in sorted(roles)]
        return "\n".join(lines + ["}"]) + "\n"

    def render_models(self) -> str:
        for name in self.schemas:
            if name not in SKIPPED_SCHEMAS and self.is_named_type(self.schemas[name]) and not self.geojson_type(self.schemas[name]):
                self.ensure_model(name)
        out = [HEADER, "namespace App.Application.Contracts;", ""]
        for i, name in enumerate(sorted(self.models)):
            if i:
                out.append("")
            out += self.models[name]
        return "\n".join(out) + "\n"


def main() -> None:
    spec_path, skeleton = Path(sys.argv[1]), Path(sys.argv[2])
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    gen = Generator(spec)
    apis, controllers = gen.render_apis()  # раньше моделей: операции регистрируют inline-типы
    models = gen.render_models()

    contracts = skeleton / "src/App.Application/Contracts/Generated"
    ctrl_dir = skeleton / "src/App.Api/Controllers/Generated"
    for d in (contracts, ctrl_dir):
        d.mkdir(parents=True, exist_ok=True)
        for old in d.glob("*.cs"):
            old.unlink()
    (contracts / "Models.cs").write_text(models, encoding="utf-8")
    (contracts / "Apis.cs").write_text(apis, encoding="utf-8")
    (contracts / "Roles.cs").write_text(gen.render_roles(), encoding="utf-8")
    for name, text in sorted(controllers.items()):
        (ctrl_dir / name).write_text(text, encoding="utf-8")
    print(f"models: {len(gen.models)}, apis/controllers: {len(controllers)} → {skeleton}")


if __name__ == "__main__":
    main()
