#!/usr/bin/env bash
# Детерминированная генерация EF-моделей из DDL (без LLM): dotnet ef dbcontext scaffold с шаблонами T4.
#   generators/gen-ef.sh <schema.sql> <backend_dir> [--verify]
# Копирует DDL в <backend_dir>/db/100_domain.sql, поднимает временный PostGIS, применяет db/*.sql, затем пишет:
#   src/App.Domain/Entities/Generated/*.cs                      — сущности (partial, без атрибутов EF)
#   src/App.Infrastructure/Persistence/Generated/AppDbContext.Generated.cs — DbSet-ы и fluent-конфигурация
#   src/App.Application/Abstractions/IAppDbContext.Generated.cs — DbSet-ы для слоя Application
# Платформенные таблицы (outbox*, idempotency* — каркас уже реализует их сам) и PostGIS пропускаются.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SCHEMA="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
OUT="$(cd "$2" && pwd)"
VERIFY="${3:-}"
IMAGE="${POSTGIS_IMAGE:-imresamu/postgis:17-3.5}"
PLATFORM_TABLES="outbox_messages idempotency_records spatial_ref_sys"

NAME="efgen-$$"
docker run -d --rm --name "$NAME" -e POSTGRES_PASSWORD=gen -e POSTGRES_DB=gen -p 127.0.0.1::5432 "$IMAGE" >/dev/null
trap 'docker rm -f "$NAME" >/dev/null 2>&1 || true' EXIT
until docker exec "$NAME" pg_isready -U postgres -d gen -q 2>/dev/null; do sleep 0.5; done
sleep 1 # первый pg_isready срабатывает до перезапуска initdb
until docker exec "$NAME" psql -U postgres -d gen -qtAc 'select 1' >/dev/null 2>&1; do sleep 0.5; done

# Доменный DDL становится частью проекта: его применяют init БД в compose и интеграционные тесты.
# Enum-типы PostgreSQL заменяются на varchar + CHECK — иначе scaffold молча теряет такие колонки.
PYTHON="${PYTHON:-python3}"
NORMALIZED="$(mktemp)"
"$PYTHON" "$HERE/ef/normalize_ddl.py" "$SCHEMA" "$NORMALIZED"
mv "$NORMALIZED" "$OUT/db/100_domain.sql"
chmod 0644 "$OUT/db/100_domain.sql"  # mktemp создаёт 0600 — контейнер PostgreSQL на Linux не прочитал бы схему
for f in "$OUT"/db/*.sql; do
  docker exec -i "$NAME" psql -U postgres -d gen -v ON_ERROR_STOP=1 -q <"$f" >/dev/null
done

PORT="$(docker port "$NAME" 5432/tcp | head -1 | sed 's/.*://')"
EXCLUDE="$(printf "'%s'," $PLATFORM_TABLES | sed 's/,$//')"
TABLES=()
while IFS= read -r t; do TABLES+=(--table "$t"); done < <(docker exec "$NAME" psql -U postgres -d gen -qtAc \
  "select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' and table_name not in ($EXCLUDE)
   and table_name not like 'outbox%' and table_name not like 'idempotency%' order by 1")

WORK="$(mktemp -d)"
trap 'docker rm -f "$NAME" >/dev/null 2>&1 || true; rm -rf "$WORK"' EXIT
(cd "$HERE/ef" && dotnet tool restore >/dev/null && dotnet ef dbcontext scaffold \
  "Host=127.0.0.1;Port=$PORT;Database=gen;Username=postgres;Password=gen" Npgsql.EntityFrameworkCore.PostgreSQL \
  --project Scaffold/Scaffold.csproj "${TABLES[@]}" \
  --context AppDbContext --context-namespace App.Infrastructure.Persistence --namespace App.Domain.Entities \
  --output-dir "$WORK/entities" --context-dir "$WORK/context" \
  --no-onconfiguring --force >"$WORK/scaffold.log" 2>&1) || { cat "$WORK/scaffold.log" >&2; exit 1; }

# Scaffold пропускает колонки/таблицы неизвестных типов лишь с предупреждением — для нас это ошибка шлюза
if grep -iE "skipping column|skipping table|unable to (scaffold|generate|identify)|could not find type mapping" "$WORK/scaffold.log" >&2; then
  echo "gen-ef: scaffold пропустил часть схемы (см. выше) — модель не совпадала бы с БД" >&2
  exit 1
fi

HEADER='// <auto-generated>
// Сгенерировано generators/gen-ef.sh из схемы БД. Не редактировать: доменное поведение — в отдельных partial-файлах.
// </auto-generated>
#nullable enable'

ENT="$OUT/src/App.Domain/Entities/Generated"
CTX="$OUT/src/App.Infrastructure/Persistence/Generated"
rm -rf "$ENT" "$CTX"
mkdir -p "$ENT" "$CTX"
# timestamptz → DateTimeOffset, как в каркасе и контрактах (Npgsql по умолчанию выдаёт DateTime).
# Безопасно, только если в схеме нет timestamp без часового пояса.
NAIVE_TS="$(docker exec "$NAME" psql -U postgres -d gen -qtAc \
  "select count(*) from information_schema.columns where table_schema='public' and data_type='timestamp without time zone'")"
fix() { # убирает BOM; при отсутствии naive timestamp меняет DateTime на DateTimeOffset
  # perl, а не sed: \b в BSD sed (macOS) не работает
  perl -pe 's/^\x{FEFF}//; s/^\xEF\xBB\xBF//' "$1" | if [[ "$NAIVE_TS" == "0" ]]; then perl -pe 's/\bDateTime\b/DateTimeOffset/g'; else cat; fi
}
for f in "$WORK"/entities/*.cs; do { echo "$HEADER"; fix "$f"; } >"$ENT/$(basename "$f")"; done
{ echo "$HEADER"; fix "$WORK/context/AppDbContext.cs"; } >"$CTX/AppDbContext.Generated.cs"

# Литеральные DEFAULT (true, 20) → инициализаторы свойств, иначе EF не сохранит false/0 (см. ef/postprocess.py)
"$PYTHON" "$HERE/ef/postprocess.py" "$CTX/AppDbContext.Generated.cs" "$ENT" >/dev/null

# IAppDbContext: те же DbSet-ы, чтобы слой Application работал с ними без ссылки на Infrastructure
{
  echo "$HEADER"
  echo "using App.Domain.Entities;"
  echo "using Microsoft.EntityFrameworkCore;"
  echo ""
  echo "namespace App.Application.Abstractions;"
  echo ""
  echo "public partial interface IAppDbContext"
  echo "{"
  grep -E '^    public DbSet<' "$CTX/AppDbContext.Generated.cs" | sed -E 's/^    public (DbSet<[A-Za-z0-9_]+>) ([A-Za-z0-9_]+) =>.*$/    \1 \2 { get; }/'
  echo "}"
} >"$OUT/src/App.Application/Abstractions/IAppDbContext.Generated.cs"

echo "entities: $(ls "$ENT" | wc -l | tr -d ' ') → $OUT"

if [[ "$VERIFY" == "--verify" ]]; then
  dotnet build "$OUT/App.slnx" -warnaserror -nologo -v q
  echo "gate dotnet: build OK"
fi
